//! The Rust emitter: types plus `encode`/`decode` written against `uo-codec`, the table state
//! and the message functions. The output is clean under the workspace lints (no indexing, no
//! lossy casts, no panics) so it can sit in a crate that denies them, and every item carries
//! `#![cfg_attr(rustfmt, rustfmt::skip)]` (the compiler never sees it) so `cargo fmt --check` leaves the file alone
//! wherever it is included.

use crate::model::{Def, EnumDef, Field, Schema, StructDef, Ty};
use crate::out::{Out, screaming, snake};

fn bytes_literal(b: &[u8]) -> String {
    b.iter().map(|x| format!("0x{x:02x}")).collect::<Vec<_>>().join(", ")
}

pub(crate) fn is_copy(schema: &Schema, ty: &Ty) -> bool {
    match ty {
        Ty::Bool | Ty::U8 | Ty::U16 | Ty::U32 | Ty::I32 | Ty::F64 | Ty::Sym | Ty::BytesRef | Ty::Ref(_) => true,
        Ty::Named(i) => matches!(schema.def(*i), Def::Enum(e) if e.unit_only),
        Ty::Utf16 | Ty::Bytes | Ty::List(_) | Ty::Columns(_) => false,
    }
}

pub(crate) fn rust_ty(schema: &Schema, ty: &Ty) -> String {
    match ty {
        Ty::Bool => "bool".into(),
        Ty::U8 => "u8".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 | Ty::Sym | Ty::BytesRef | Ty::Ref(_) => "u32".into(),
        Ty::I32 => "i32".into(),
        Ty::F64 => "f64".into(),
        Ty::Utf16 => "Vec<u16>".into(),
        Ty::Bytes => "Vec<u8>".into(),
        Ty::Named(i) => schema.def(*i).name().to_string(),
        Ty::List(inner) => format!("Vec<{}>", rust_ty(schema, inner)),
        Ty::Columns(i) => format!("{}Columns", schema.def(*i).name()),
    }
}

fn field_ty(schema: &Schema, f: &Field) -> String {
    let t = rust_ty(schema, &f.ty);
    if f.optional { format!("Option<{t}>") } else { t }
}

fn table_ref(schema: &Schema, t: usize) -> (usize, &str) {
    (t, schema.tables[t].name.as_str())
}

/// Statements that write a value of `ty`. `x` is an expression: a value for a `Copy` type, otherwise a
/// place or a reference (`x_ref`: it already is a reference).
fn enc(schema: &Schema, o: &mut Out, ty: &Ty, x: &str, x_ref: bool, depth: usize) {
    let as_ref = if x_ref { x.to_string() } else { format!("&{x}") };
    match ty {
        Ty::Bool => o.line(&format!("w.bool({x});")),
        Ty::U8 => o.line(&format!("w.u8({x});")),
        Ty::U16 => o.line(&format!("w.u16({x});")),
        Ty::U32 | Ty::Sym | Ty::BytesRef | Ty::Ref(_) => o.line(&format!("w.u32({x});")),
        Ty::I32 => o.line(&format!("w.i32({x});")),
        Ty::F64 => o.line(&format!("w.f64({x});")),
        Ty::Utf16 => o.line(&format!("w.utf16({as_ref});")),
        Ty::Bytes => o.line(&format!("w.bytes({as_ref});")),
        Ty::Named(_) | Ty::Columns(_) => o.line(&format!("{x}.encode(w);")),
        Ty::List(inner) => match **inner {
            Ty::Bool => o.line(&format!("w.bit_list({as_ref});")),
            Ty::U8 => o.line(&format!("w.bytes({as_ref});")),
            _ => {
                o.line(&format!("w.len({x}.len());"));
                let e = format!("e{depth}");
                let copy = is_copy(schema, inner);
                o.open(&format!("for {e} in {x}.iter(){} {{", if copy { ".copied()" } else { "" }));
                enc(schema, o, inner, &e, !copy, depth + 1);
                o.close("}");
            }
        },
    }
}

/// An expression that reads a value of `ty`.
fn dec(schema: &Schema, ty: &Ty) -> String {
    match ty {
        Ty::Bool => "r.bool()?".into(),
        Ty::U8 => "r.u8()?".into(),
        Ty::U16 => "r.u16()?".into(),
        Ty::U32 | Ty::BytesRef => "r.u32()?".into(),
        Ty::I32 => "r.i32()?".into(),
        Ty::F64 => "r.f64()?".into(),
        Ty::Utf16 => "r.utf16()?".into(),
        Ty::Bytes => "r.bytes()?".into(),
        Ty::Sym => "r.ref_in(0, \"sym\")?".into(),
        Ty::Ref(t) => {
            let (i, name) = table_ref(schema, *t);
            format!("r.ref_in({i}, \"{name}\")?")
        }
        Ty::Named(i) => format!("{}::decode(r)?", schema.def(*i).name()),
        Ty::Columns(i) => format!("{}Columns::decode(r)?", schema.def(*i).name()),
        Ty::List(inner) => match **inner {
            Ty::Bool => "r.bit_list()?".into(),
            Ty::U8 => "r.bytes()?".into(),
            _ => {
                let min = schema.list_elem_min_bits(inner);
                format!(
                    "{{ let n = r.list_of::<{}>({min})?; let mut v = Vec::with_capacity(n); for _ in 0..n {{ v.push({}); }} v }}",
                    rust_ty(schema, inner),
                    dec(schema, inner)
                )
            }
        },
    }
}

pub fn emit(schema: &Schema, source: &str) -> String {
    let mut o = Out::new("    ");
    o.line(&format!(
        "// @generated by core/tools/uo-schema from {source} (schema `{}`, hash {}). Do not edit: change the .uos file and run `cargo run -p uo-schema -- generate`.",
        schema.name,
        schema.hash_hex()
    ));
    o.line("#![cfg_attr(rustfmt, rustfmt::skip)]");
    o.line("#![allow(clippy::needless_range_loop, clippy::large_enum_variant, clippy::redundant_field_names, clippy::enum_variant_names)]");
    o.blank();
    o.line("#[allow(unused_imports)]");
    o.line("use uo_codec::{DecodeError, EncodeError, Limits, Reader, TableDelta, Writer, bit, bit_at};");
    o.blank();
    o.line(&format!("pub const NAME: &str = \"{}\";", schema.name));
    o.line(&format!("pub const MAGIC: [u8; 4] = [{}];", bytes_literal(&schema.magic)));
    o.line(&format!("pub const SCHEMA_HASH: [u8; 8] = [{}];", bytes_literal(&schema.hash)));
    for (id, m) in schema.messages.iter().enumerate() {
        o.line(&format!("pub const MSG_{}: u32 = {id};", screaming(schema.def(*m).name())));
    }
    o.blank();
    for d in &schema.defs {
        match d {
            Def::Struct(s) => {
                emit_struct(schema, &mut o, s);
                if s.columns_used {
                    emit_columns(schema, &mut o, s);
                }
            }
            Def::Enum(e) => emit_enum(schema, &mut o, e),
        }
    }
    emit_tables(schema, &mut o);
    for m in &schema.messages {
        emit_message(schema, &mut o, schema.struct_def(*m));
    }
    o.finish()
}

fn emit_struct(schema: &Schema, o: &mut Out, s: &StructDef) {
    o.docs("/// ", &s.doc);
    o.line("#[derive(Debug, Clone, PartialEq)]");
    o.open(&format!("pub struct {} {{", s.name));
    for f in &s.fields {
        o.docs("/// ", &f.doc);
        o.line(&format!("pub {}: {},", f.rname, field_ty(schema, f)));
    }
    o.close("}");
    o.blank();
    o.open(&format!("impl {} {{", s.name));
    o.line("/// The least number of bits an element takes on the wire.");
    o.line(&format!("pub const MIN_BITS: u64 = {};", s.min_bits));
    o.blank();
    o.open("pub fn encode(&self, w: &mut Writer<'_>) {");
    let bits: Vec<String> = s
        .fields
        .iter()
        .filter(|f| f.is_bit())
        .map(|f| if f.optional { format!("self.{}.is_some()", f.rname) } else { format!("self.{}", f.rname) })
        .collect();
    if !bits.is_empty() {
        o.line(&format!("w.bitmap(&[{}]);", bits.join(", ")));
    }
    for f in &s.fields {
        let copy = is_copy(schema, &f.ty);
        if f.optional {
            if copy {
                o.open(&format!("if let Some(v) = self.{} {{", f.rname));
            } else {
                o.open(&format!("if let Some(v) = &self.{} {{", f.rname));
            }
            enc(schema, o, &f.ty, "v", !copy, 0);
            o.close("}");
        } else if f.ty != Ty::Bool {
            enc(schema, o, &f.ty, &format!("self.{}", f.rname), false, 0);
        }
    }
    o.close("}");
    o.blank();
    o.open("pub fn decode(r: &mut Reader<'_>) -> Result<Self, DecodeError> {");
    if s.recursive {
        o.line("r.enter()?;");
    }
    let nbits = s.bit_fields();
    if nbits > 0 {
        o.line(&format!("let bm = r.bitmap({nbits})?;"));
    }
    let mut bit_i = 0usize;
    for f in &s.fields {
        if f.optional {
            o.line(&format!("let f_{} = if bit(bm, {bit_i}) {{ Some({}) }} else {{ None }};", f.name, dec(schema, &f.ty)));
            bit_i += 1;
        } else if f.ty == Ty::Bool {
            o.line(&format!("let f_{} = bit(bm, {bit_i});", f.name));
            bit_i += 1;
        } else {
            o.line(&format!("let f_{} = {};", f.name, dec(schema, &f.ty)));
        }
    }
    if s.recursive {
        o.line("r.leave();");
    }
    let init: Vec<String> = s.fields.iter().map(|f| format!("{r}: f_{n}", r = f.rname, n = f.name)).collect();
    o.line(&format!("Ok(Self {{ {} }})", init.join(", ")));
    o.close("}");
    o.close("}");
    o.blank();
}

fn emit_columns(schema: &Schema, o: &mut Out, s: &StructDef) {
    let name = format!("{}Columns", s.name);
    o.line(&format!("/// `columns<{}>`: the fields stored one column at a time (all of the first, then all of the second...).", s.name));
    o.line("#[derive(Debug, Clone, PartialEq, Default)]");
    o.open(&format!("pub struct {name} {{"));
    for f in &s.fields {
        o.docs("/// ", &f.doc);
        let t = rust_ty(schema, &f.ty);
        o.line(&format!("pub {}: Vec<{}>,", f.rname, if f.optional { format!("Option<{t}>") } else { t }));
    }
    o.close("}");
    o.blank();
    o.open(&format!("impl {name} {{"));
    o.line("/// The least number of bits a row takes on the wire.");
    o.line(&format!("pub const MIN_BITS: u64 = {};", s.columns_min_bits));
    o.blank();
    o.line("/// The number of rows (the columns must all have this length to be encoded).");
    o.open("pub fn len(&self) -> usize {");
    o.line(&format!("self.{}.len()", s.fields[0].rname));
    o.close("}");
    o.blank();
    o.open("pub fn is_empty(&self) -> bool {");
    o.line("self.len() == 0");
    o.close("}");
    o.blank();
    o.open("pub fn encode(&self, w: &mut Writer<'_>) {");
    o.line("let n = self.len();");
    let others: Vec<String> = s.fields.iter().skip(1).map(|f| format!("self.{}.len() != n", f.rname)).collect();
    if !others.is_empty() {
        o.open(&format!("if {} {{", others.join(" || ")));
        o.line(&format!("w.fail(EncodeError::ColumnLengths(\"{}\"));", s.name));
        o.line("return;");
        o.close("}");
    }
    o.line("w.len(n);");
    for f in &s.fields {
        let copy = is_copy(schema, &f.ty);
        if f.optional {
            o.line(&format!("w.bits(self.{}.iter().map(Option::is_some));", f.rname));
            o.open(&format!("for e0 in self.{}.iter().flatten(){} {{", f.rname, if copy { ".copied()" } else { "" }));
            enc(schema, o, &f.ty, "e0", !copy, 1);
            o.close("}");
        } else if f.ty == Ty::Bool {
            o.line(&format!("w.bits(self.{}.iter().copied());", f.rname));
        } else {
            o.open(&format!("for e0 in self.{}.iter(){} {{", f.rname, if copy { ".copied()" } else { "" }));
            enc(schema, o, &f.ty, "e0", !copy, 1);
            o.close("}");
        }
    }
    o.close("}");
    o.blank();
    o.open("pub fn decode(r: &mut Reader<'_>) -> Result<Self, DecodeError> {");
    o.line("let n = r.list_len(Self::MIN_BITS)?;");
    let sizes: Vec<String> = s
        .fields
        .iter()
        .map(|f| {
            format!(
                "std::mem::size_of::<{}>()",
                if f.optional { format!("Option<{}>", rust_ty(schema, &f.ty)) } else { rust_ty(schema, &f.ty) }
            )
        })
        .collect();
    o.line(&format!("r.charge_alloc(n, {})?;", sizes.join(" + ")));
    for f in &s.fields {
        if f.optional {
            o.line(&format!("let present_{} = r.bits(n)?;", f.name));
            o.line(&format!("let mut c_{} = Vec::with_capacity(n);", f.name));
            o.open("for i in 0..n {");
            o.line(&format!("c_{}.push(if bit_at(present_{}, i) {{ Some({}) }} else {{ None }});", f.name, f.name, dec(schema, &f.ty)));
            o.close("}");
        } else if f.ty == Ty::Bool {
            o.line(&format!("let flags_{} = r.bits(n)?;", f.name));
            o.line(&format!("let c_{}: Vec<bool> = (0..n).map(|i| bit_at(flags_{}, i)).collect();", f.name, f.name));
        } else {
            o.line(&format!("let mut c_{} = Vec::with_capacity(n);", f.name));
            o.line(&format!("for _ in 0..n {{ c_{}.push({}); }}", f.name, dec(schema, &f.ty)));
        }
    }
    let init: Vec<String> = s.fields.iter().map(|f| format!("{r}: c_{n}", r = f.rname, n = f.name)).collect();
    o.line(&format!("Ok(Self {{ {} }})", init.join(", ")));
    o.close("}");
    o.close("}");
    o.blank();
}

fn emit_enum(schema: &Schema, o: &mut Out, e: &EnumDef) {
    o.docs("/// ", &e.doc);
    if e.unit_only {
        o.line("#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    } else {
        o.line("#[derive(Debug, Clone, PartialEq)]");
    }
    o.open(&format!("pub enum {} {{", e.name));
    for v in &e.variants {
        o.docs("/// ", &v.doc);
        match &v.payload {
            Some(t) => o.line(&format!("{}({}),", v.name, rust_ty(schema, t))),
            None => o.line(&format!("{},", v.name)),
        }
    }
    o.close("}");
    o.blank();
    o.open(&format!("impl {} {{", e.name));
    o.line("/// The least number of bits a value takes on the wire.");
    o.line(&format!("pub const MIN_BITS: u64 = {};", e.min_bits));
    o.blank();
    o.open("pub fn encode(&self, w: &mut Writer<'_>) {");
    o.open("match self {");
    for (i, v) in e.variants.iter().enumerate() {
        match &v.payload {
            Some(t) => {
                o.open(&format!("Self::{}(v) => {{", v.name));
                o.line(&format!("w.u32({i});"));
                let copy = is_copy(schema, t);
                if copy {
                    o.line("let v = *v;");
                }
                enc(schema, o, t, "v", !copy, 0);
                o.close("}");
            }
            None => o.line(&format!("Self::{} => w.u32({i}),", v.name)),
        }
    }
    o.close("}");
    o.close("}");
    o.blank();
    o.open("pub fn decode(r: &mut Reader<'_>) -> Result<Self, DecodeError> {");
    if e.recursive {
        o.line("r.enter()?;");
    }
    o.line("let tag = r.u32()?;");
    o.open("let value = match tag {");
    for (i, v) in e.variants.iter().enumerate() {
        match &v.payload {
            Some(t) => o.line(&format!("{i} => Self::{}({}),", v.name, dec(schema, t))),
            None => o.line(&format!("{i} => Self::{},", v.name)),
        }
    }
    o.line(&format!("_ => return Err(DecodeError::BadTag {{ ty: \"{}\", tag }}),", e.name));
    o.close("};");
    if e.recursive {
        o.line("r.leave();");
    }
    o.line("Ok(value)");
    o.close("}");
    o.close("}");
    o.blank();
}

fn emit_tables(schema: &Schema, o: &mut Out) {
    let ty_of = |t: &crate::model::Table| match t.entry {
        None => "Vec<u16>".to_string(),
        Some(e) => schema.def(e).name().to_string(),
    };
    o.line("/// What a decoder has received so far in one generation: the entries of every table (ids are positions).");
    o.line("#[derive(Debug, Clone, Default, PartialEq)]");
    o.open("pub struct Tables {");
    o.line("/// The generation the entries belong to (`None` before the first message).");
    o.line("pub generation: Option<u32>,");
    for t in &schema.tables {
        o.line(&format!("pub {}: Vec<{}>,", t.name, ty_of(t)));
    }
    o.close("}");
    o.blank();
    let n = schema.tables.len();
    o.open("impl Tables {");
    o.open("pub fn new() -> Self {");
    o.line("Self::default()");
    o.close("}");
    o.blank();
    o.open("pub fn clear(&mut self) {");
    o.line("*self = Self::default();");
    o.close("}");
    o.blank();
    o.line("/// The number of entries of every table, in declaration order.");
    o.open(&format!("pub fn lens(&self) -> [usize; {n}] {{"));
    let lens: Vec<String> = schema.tables.iter().map(|t| format!("self.{}.len()", t.name)).collect();
    o.line(&format!("[{}]", lens.join(", ")));
    o.close("}");
    o.blank();
    o.line("/// Drops the entries past `lens` (a failed message leaves the tables as they were).");
    o.open(&format!("pub fn truncate(&mut self, lens: &[usize; {n}]) {{"));
    let names: Vec<String> = (0..n).map(|i| format!("l{i}")).collect();
    o.line(&format!("let [{}] = *lens;", names.join(", ")));
    for (i, t) in schema.tables.iter().enumerate() {
        o.line(&format!("self.{}.truncate(l{i});", t.name));
    }
    o.close("}");
    o.blank();
    o.line("/// The entries past `lens` as the delta that would carry them (the generation is the tables').");
    o.open(&format!("pub fn delta_since(&self, lens: &[usize; {n}]) -> Delta {{"));
    o.line(&format!("let [{}] = *lens;", names.join(", ")));
    o.line("Delta {");
    o.line("    generation: self.generation.unwrap_or(0),");
    for (i, t) in schema.tables.iter().enumerate() {
        o.line(&format!(
            "    {n}: TableDelta {{ from: u32::try_from(l{i}).unwrap_or(0), items: self.{n}.get(l{i}..).unwrap_or(&[]).to_vec() }},",
            n = t.name
        ));
    }
    o.line("}");
    o.close("}");
    if schema.uses_sym() {
        o.blank();
        o.line("/// The code units of symbol `id` (empty for an id the table does not have).");
        o.open("pub fn sym_units(&self, id: u32) -> &[u16] {");
        o.line("usize::try_from(id).ok().and_then(|i| self.sym.get(i)).map_or(&[], Vec::as_slice)");
        o.close("}");
    }
    o.close("}");
    o.blank();
    o.line("/// The new entries a message carries, per table, and its generation (the encoder's input).");
    o.line("#[derive(Debug, Clone, Default, PartialEq)]");
    o.open("pub struct Delta {");
    o.line("pub generation: u32,");
    for t in &schema.tables {
        o.line(&format!("pub {}: TableDelta<{}>,", t.name, ty_of(t)));
    }
    o.close("}");
    o.blank();
    o.line("/// The id and generation of a message, after the magic and the schema hash were checked.");
    o.open("pub fn peek_header(buf: &[u8]) -> Result<uo_codec::Header, DecodeError> {");
    o.line("Reader::new(buf, &Limits::default()).header(&MAGIC, &SCHEMA_HASH)");
    o.close("}");
    o.blank();
}

fn emit_message(schema: &Schema, o: &mut Out, m: &StructDef) {
    let fname = snake(&m.name);
    let konst = format!("MSG_{}", screaming(&m.name));
    o.line(&format!("/// Writes a `{}` message: the header, the new table entries of `delta`, the body.", m.name));
    o.line("/// On an error `out` is left as it was.");
    o.open(&format!("pub fn encode_{fname}(out: &mut Vec<u8>, delta: &Delta, msg: &{}) -> Result<(), EncodeError> {{", m.name));
    o.line("let mut w = Writer::new(out);");
    o.line(&format!("w.header(&MAGIC, &SCHEMA_HASH, {konst}, delta.generation);"));
    for t in &schema.tables {
        o.line(&format!("w.u32(delta.{n}.from);", n = t.name));
        o.line(&format!("w.len(delta.{n}.items.len());", n = t.name));
    }
    for t in &schema.tables {
        match t.entry {
            None => o.line(&format!("for e in delta.{}.items.iter() {{ w.utf16(e); }}", t.name)),
            Some(_) => o.line(&format!("for e in delta.{}.items.iter() {{ e.encode(&mut w); }}", t.name)),
        }
    }
    o.line("msg.encode(&mut w);");
    o.line("w.finish()");
    o.close("}");
    o.blank();
    o.line(&format!("/// Reads a `{}` message. `tables` is the state of this stream of messages: the new entries are", m.name));
    o.line("/// appended, a new generation replaces them, and an error leaves them as they were.");
    o.open(&format!("pub fn decode_{fname}(buf: &[u8], tables: &mut Tables, limits: &Limits) -> Result<{}, DecodeError> {{", m.name));
    o.line("let mut r = Reader::new(buf, limits);");
    o.line("let head = r.header(&MAGIC, &SCHEMA_HASH)?;");
    o.open(&format!("if head.message != {konst} {{"));
    o.line(&format!("return Err(DecodeError::WrongMessage {{ expected: {konst}, found: head.message }});"));
    o.close("}");
    o.line("let previous = if tables.generation == Some(head.generation) { None } else { Some(std::mem::take(tables)) };");
    o.line("let lens = tables.lens();");
    o.open(&format!("match decode_{fname}_body(&mut r, tables) {{"));
    o.open("Ok(msg) => {");
    o.line("tables.generation = Some(head.generation);");
    o.line("Ok(msg)");
    o.close("}");
    o.open("Err(e) => {");
    o.line("match previous { Some(p) => *tables = p, None => tables.truncate(&lens) }");
    o.line("Err(e)");
    o.close("}");
    o.close("}");
    o.close("}");
    o.blank();
    let tables_param = if schema.tables.is_empty() { "_tables" } else { "tables" };
    o.open(&format!("fn decode_{fname}_body(r: &mut Reader<'_>, {tables_param}: &mut Tables) -> Result<{}, DecodeError> {{", m.name));
    for (i, t) in schema.tables.iter().enumerate() {
        o.line(&format!("let n_{n} = r.table_header({i}, \"{n}\", tables.{n}.len(), {})?;", t.min_bits, n = t.name));
    }
    for t in &schema.tables {
        match t.entry {
            None => o.line(&format!(
                "r.charge_alloc(n_{n}, std::mem::size_of::<Vec<u16>>())?; for _ in 0..n_{n} {{ tables.{n}.push(r.utf16()?); }}",
                n = t.name
            )),
            Some(e) => o.line(&format!(
                "r.charge_alloc(n_{n}, std::mem::size_of::<{e}>())?; for _ in 0..n_{n} {{ tables.{n}.push({e}::decode(r)?); }}",
                e = schema.def(e).name(),
                n = t.name
            )),
        }
    }
    o.line(&format!("let msg = {}::decode(r)?;", m.name));
    o.line("r.end()?;");
    o.line("Ok(msg)");
    o.close("}");
    o.blank();
}
