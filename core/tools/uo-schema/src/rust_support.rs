//! The Rust test-support emitter: a canonical text dump (compared with the TypeScript dump to
//! prove both decoders read the same values) and a seeded random generator of valid messages
//! (round-trip property tests, fuzz seeds). Generated beside the main file and declared as a
//! sibling module; it is test code and not held to the lints of the main file.

use crate::model::{Def, EnumDef, Schema, StructDef, Ty};
use crate::out::Out;
use crate::rust::{is_copy, rust_ty};

fn dump_stmt(schema: &Schema, o: &mut Out, ty: &Ty, x: &str, x_ref: bool, depth: usize) {
    let as_ref = if x_ref { x.to_string() } else { format!("&{x}") };
    match ty {
        Ty::Bool => o.line(&format!("out.push_str(if {x} {{ \"true\" }} else {{ \"false\" }});")),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::I32 | Ty::BytesRef | Ty::Ref(_) => o.line(&format!("uo_codec::dump::u(out, {x});")),
        Ty::F64 => o.line(&format!("uo_codec::dump::f64(out, {x});")),
        Ty::Utf16 => o.line(&format!("uo_codec::dump::utf16(out, {as_ref});")),
        Ty::Sym => o.line(&format!("uo_codec::dump::utf16(out, t.sym_units({x}));")),
        Ty::Bytes => o.line(&format!("uo_codec::dump::bytes(out, {as_ref});")),
        Ty::Named(_) | Ty::Columns(_) => o.line(&format!("{x}.dump(out, t);")),
        Ty::List(inner) => match **inner {
            Ty::U8 => o.line(&format!("uo_codec::dump::bytes(out, {as_ref});")),
            _ => {
                let e = format!("e{depth}");
                let copy = is_copy(schema, inner);
                o.line("out.push('[');");
                o.open(&format!("for (i{depth}, {e}) in {x}.iter(){}.enumerate() {{", if copy { ".copied()" } else { "" }));
                o.line(&format!("if i{depth} > 0 {{ out.push(','); }}"));
                dump_stmt(schema, o, inner, &e, !copy, depth + 1);
                o.close("}");
                o.line("out.push(']');");
            }
        },
    }
}

fn rand_expr(schema: &Schema, ty: &Ty) -> String {
    match ty {
        Ty::Bool => "rng.bool()".into(),
        Ty::U8 => "rng.u8()".into(),
        Ty::U16 => "rng.u16()".into(),
        Ty::U32 | Ty::BytesRef => "rng.u32_edge()".into(),
        Ty::I32 => "rng.i32_edge()".into(),
        Ty::F64 => "rng.f64_edge()".into(),
        Ty::Utf16 => "rng.utf16(6)".into(),
        Ty::Bytes => "rng.bytes(8)".into(),
        Ty::Sym => "rng.below(b.sym)".into(),
        Ty::Ref(t) => format!("rng.below(b.{})", schema.tables[*t].name),
        Ty::Named(i) => format!("{}::random(rng, b, depth + 1)", schema.def(*i).name()),
        Ty::Columns(i) => format!("{}Columns::random(rng, b, depth + 1)", schema.def(*i).name()),
        Ty::List(inner) => match **inner {
            Ty::U8 => "rng.bytes(8)".into(),
            _ => format!(
                "{{ let n = if depth > 3 {{ 0 }} else if depth == 0 && rng.below(48) == 0 {{ 130 + rng.below(100) }} else {{ rng.below(4) }}; (0..n).map(|_| {}).collect::<Vec<_>>() }}",
                rand_expr(schema, inner)
            ),
        },
    }
}

pub fn emit(schema: &Schema, source: &str, main_module: &str) -> String {
    let mut o = Out::new("    ");
    o.line(&format!(
        "// @generated by core/tools/uo-schema from {source} (schema `{}`, hash {}): test support (canonical dump, random messages). Do not edit.",
        schema.name,
        schema.hash_hex()
    ));
    o.line("#![cfg_attr(rustfmt, rustfmt::skip)]");
    o.line("#![allow(clippy::all, unused_imports, unused_variables, unused_mut)]");
    o.blank();
    o.line(&format!("use super::{main_module}::*;"));
    o.line("use uo_codec::testing::Rng;");
    o.blank();
    o.line("/// The number of entries each table has (the bound of its ids) when a message is built.");
    o.line("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]");
    o.open("pub struct Bounds {");
    for t in &schema.tables {
        o.line(&format!("pub {}: u32,", t.name));
    }
    o.close("}");
    o.blank();
    for d in &schema.defs {
        match d {
            Def::Struct(s) => {
                dump_struct(schema, &mut o, s);
                random_struct(schema, &mut o, s);
                if s.columns_used {
                    columns_support(schema, &mut o, s);
                }
            }
            Def::Enum(e) => enum_support(schema, &mut o, e),
        }
    }
    tables_support(schema, &mut o);
    for m in &schema.messages {
        let s = schema.struct_def(*m);
        let f = crate::out::snake(&s.name);
        o.open(&format!("pub fn dump_{f}(msg: &{}, t: &Tables) -> String {{", s.name));
        o.line("let mut out = String::new();");
        o.line("msg.dump(&mut out, t);");
        o.line("out");
        o.close("}");
        o.blank();
    }
    o.finish()
}

fn dump_struct(schema: &Schema, o: &mut Out, s: &StructDef) {
    o.open(&format!("impl {} {{", s.name));
    o.open("pub fn dump(&self, out: &mut String, t: &Tables) {");
    o.line("out.push('{');");
    for (i, f) in s.fields.iter().enumerate() {
        o.line(&format!("out.push_str(\"{}{}:\");", if i > 0 { "," } else { "" }, f.name));
        let copy = is_copy(schema, &f.ty);
        if f.optional {
            o.open(&format!("match {}self.{} {{", if copy { "" } else { "&" }, f.rname));
            o.open("Some(v) => {");
            dump_stmt(schema, o, &f.ty, "v", !copy, 0);
            o.close("}");
            o.line("None => out.push('-'),");
            o.close("}");
        } else {
            dump_stmt(schema, o, &f.ty, &format!("self.{}", f.rname), false, 0);
        }
    }
    o.line("out.push('}');");
    o.close("}");
    o.close("}");
    o.blank();
}

fn random_struct(schema: &Schema, o: &mut Out, s: &StructDef) {
    o.open(&format!("impl {} {{", s.name));
    o.open("pub fn random(rng: &mut Rng, b: &Bounds, depth: u32) -> Self {");
    let fields: Vec<String> = s
        .fields
        .iter()
        .map(|f| {
            let e = rand_expr(schema, &f.ty);
            if f.optional { format!("{}: if rng.bool() {{ Some({e}) }} else {{ None }}", f.rname) } else { format!("{}: {e}", f.rname) }
        })
        .collect();
    o.line("Self {");
    for f in &fields {
        o.line(&format!("    {f},"));
    }
    o.line("}");
    o.close("}");
    o.close("}");
    o.blank();
}

fn columns_support(schema: &Schema, o: &mut Out, s: &StructDef) {
    let name = format!("{}Columns", s.name);
    o.open(&format!("impl {name} {{"));
    o.open("pub fn dump(&self, out: &mut String, t: &Tables) {");
    o.line("out.push('[');");
    o.open("for i in 0..self.len() {");
    o.line("if i > 0 { out.push(','); }");
    o.line("out.push('{');");
    for (i, f) in s.fields.iter().enumerate() {
        o.line(&format!("out.push_str(\"{}{}:\");", if i > 0 { "," } else { "" }, f.name));
        let copy = is_copy(schema, &f.ty);
        let pat = |inner: &str| if copy { format!("&{inner}") } else { inner.to_string() };
        if f.optional {
            o.open(&format!("match self.{}.get(i) {{", f.rname));
            o.open(&format!("Some({}) => {{", pat("Some(v)")));
            dump_stmt(schema, o, &f.ty, "v", !copy, 0);
            o.close("}");
            o.line("_ => out.push('-'),");
            o.close("}");
        } else {
            o.open(&format!("if let Some({}) = self.{}.get(i) {{", pat("v"), f.rname));
            dump_stmt(schema, o, &f.ty, "v", !copy, 0);
            o.close("}");
        }
    }
    o.line("out.push('}');");
    o.close("}");
    o.line("out.push(']');");
    o.close("}");
    o.blank();
    o.open("pub fn random(rng: &mut Rng, b: &Bounds, depth: u32) -> Self {");
    o.line("let n = if depth > 3 { 0 } else if depth == 0 && rng.below(16) == 0 { 130 + rng.below(100) } else { rng.below(5) };");
    o.line("Self {");
    for f in &s.fields {
        let e = rand_expr(schema, &f.ty);
        if f.optional {
            o.line(&format!("    {}: (0..n).map(|_| if rng.bool() {{ Some({e}) }} else {{ None }}).collect(),", f.rname));
        } else {
            o.line(&format!("    {}: (0..n).map(|_| {e}).collect(),", f.rname));
        }
    }
    o.line("}");
    o.close("}");
    o.close("}");
    o.blank();
}

fn enum_support(schema: &Schema, o: &mut Out, e: &EnumDef) {
    o.open(&format!("impl {} {{", e.name));
    o.open("pub fn dump(&self, out: &mut String, t: &Tables) {");
    o.open("match self {");
    for v in &e.variants {
        match &v.payload {
            Some(ty) => {
                o.open(&format!("Self::{}(v) => {{", v.name));
                o.line(&format!("out.push_str(\"{}(\");", v.name));
                let copy = is_copy(schema, ty);
                if copy {
                    o.line("let v = *v;");
                }
                dump_stmt(schema, o, ty, "v", !copy, 0);
                o.line("out.push(')');");
                o.close("}");
            }
            None => o.line(&format!("Self::{} => out.push_str(\"{}\"),", v.name, v.name)),
        }
    }
    o.close("}");
    o.close("}");
    o.blank();
    o.open("pub fn random(rng: &mut Rng, b: &Bounds, depth: u32) -> Self {");
    o.open(&format!("match rng.below({}) {{", e.variants.len()));
    for (i, v) in e.variants.iter().enumerate() {
        let last = i + 1 == e.variants.len();
        let pat = if last { "_".to_string() } else { i.to_string() };
        match &v.payload {
            Some(ty) => o.line(&format!("{pat} => Self::{}({}),", v.name, rand_expr(schema, ty))),
            None => o.line(&format!("{pat} => Self::{},", v.name)),
        }
    }
    o.close("}");
    o.close("}");
    o.close("}");
    o.blank();
    let _ = rust_ty;
}

fn tables_support(schema: &Schema, o: &mut Out) {
    o.line("/// Dumps every table entry (the entries a stream of messages carried).");
    o.open("pub fn dump_tables(tables: &Tables) -> String {");
    o.line("let t = tables;");
    o.line("let mut out = String::new();");
    for tb in &schema.tables {
        o.line(&format!("out.push_str(\"{}=[\");", tb.name));
        o.open(&format!("for (i, e) in t.{}.iter().enumerate() {{", tb.name));
        o.line("if i > 0 { out.push(','); }");
        match tb.entry {
            None => o.line("uo_codec::dump::utf16(&mut out, e);"),
            Some(_) => o.line("e.dump(&mut out, t);"),
        }
        o.close("}");
        o.line("out.push_str(\"];\");");
    }
    o.line("out");
    o.close("}");
    o.blank();
    o.line("/// The new entries of one message (`first`: at least one per table, so ids can refer to something), and the bounds the body may use.");
    o.open("pub fn random_delta(rng: &mut Rng, tables: &Tables, generation: u32, first: bool) -> (Delta, Bounds) {");
    o.line("let mut d = Delta { generation, ..Delta::default() };");
    o.line("let mut b = Bounds::default();");
    for tb in &schema.tables {
        let n = &tb.name;
        o.line(&format!("let from_{n} = u32::try_from(tables.{n}.len()).unwrap_or(0);"));
        o.line(&format!("let count_{n} = if first {{ 1 + rng.below(3) }} else {{ rng.below(3) }};"));
        o.line(&format!("d.{n}.from = from_{n};"));
        o.line(&format!("b.{n} = from_{n} + count_{n};"));
    }
    for tb in &schema.tables {
        let n = &tb.name;
        match tb.entry {
            None => o.line(&format!("for i in 0..count_{n} {{ d.{n}.items.push(rng.unique_utf16(from_{n} + i, 4)); }}")),
            Some(e) => o.line(&format!("for _ in 0..count_{n} {{ d.{n}.items.push({}::random(rng, &b, 1)); }}", schema.def(e).name())),
        }
    }
    o.line("(d, b)");
    o.close("}");
    o.blank();
    o.line("/// Appends the entries of `delta` to `tables` (what the decoder does), so a following delta starts after them.");
    o.open("pub fn apply_delta(tables: &mut Tables, delta: &Delta) {");
    o.line("if tables.generation != Some(delta.generation) { tables.clear(); tables.generation = Some(delta.generation); }");
    for tb in &schema.tables {
        o.line(&format!("tables.{n}.extend(delta.{n}.items.iter().cloned());", n = tb.name));
    }
    o.close("}");
    o.blank();
}
