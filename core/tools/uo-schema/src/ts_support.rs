//! The TypeScript test-support emitter: the canonical text dump (the format of the Rust
//! `*_support.rs` dump, so the two decoders can be compared field by field).

use crate::model::ts_acc;
use crate::model::{Def, EnumDef, Schema, StructDef, Ty};
use crate::out::Out;
use crate::ts::table_prop;

fn dump_expr(schema: &Schema, ty: &Ty, x: &str, depth: usize) -> String {
    match ty {
        Ty::Bool => format!("({x} ? \"true\" : \"false\")"),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::I32 | Ty::BytesRef | Ty::Ref(_) => format!("String({x})"),
        Ty::F64 => format!("f64({x})"),
        Ty::Utf16 | Ty::Sym => format!("str({x})"),
        Ty::Bytes => format!("bytes({x})"),
        Ty::Named(i) => format!("dump{}({x}, t)", schema.def(*i).name()),
        Ty::Columns(i) => format!("dump{}Columns({x}, t)", schema.def(*i).name()),
        Ty::List(inner) => match **inner {
            Ty::U8 => format!("bytes({x})"),
            _ => {
                let e = format!("e{depth}");
                format!("\"[\" + {x}.map(({e}) => {}).join(\",\") + \"]\"", dump_expr(schema, inner, &e, depth + 1))
            }
        },
    }
}

fn struct_expr(s: &StructDef, schema: &Schema, v: &str) -> String {
    let mut parts = vec!["\"{\"".to_string()];
    for (i, f) in s.fields.iter().enumerate() {
        parts.push(format!("\"{}{}:\"", if i > 0 { "," } else { "" }, f.name));
        let x = format!("{v}{}", ts_acc(&f.ts_name));
        if f.optional {
            parts.push(format!("({x} === undefined ? \"-\" : {})", dump_expr(schema, &f.ty, &x, 0)));
        } else {
            parts.push(dump_expr(schema, &f.ty, &x, 0));
        }
    }
    parts.push("\"}\"".to_string());
    parts.join(" + ")
}

pub fn emit(schema: &Schema, source: &str, main_import: &str) -> String {
    let mut o = Out::new("  ");
    o.line(&format!(
        "// @generated by core/tools/uo-schema from {source} (schema `{}`, hash {}): test support (canonical dump). Do not edit.",
        schema.name,
        schema.hash_hex()
    ));
    o.blank();
    let names: Vec<String> = schema.defs.iter().map(|d| format!("type {}", d.name())).collect();
    let mut imports = names;
    imports.push("type Tables".to_string());
    o.line(&format!("import {{ {} }} from \"{main_import}\";", imports.join(", ")));
    o.blank();
    o.line("const dv = new DataView(new ArrayBuffer(8));");
    o.line("const hex = (v: number, n: number): string => v.toString(16).padStart(n, \"0\");");
    o.open("function f64(v: number): string {");
    o.line("if (v !== v) return \"f:7ff8000000000000\";");
    o.line("dv.setFloat64(0, v, true);");
    o.line("return \"f:\" + hex(dv.getUint32(4, true), 8) + hex(dv.getUint32(0, true), 8);");
    o.close("}");
    o.open("function str(s: string): string {");
    o.line("let out = \"\\\"\";");
    o.line("for (let i = 0; i < s.length; i++) out += hex(s.charCodeAt(i), 4);");
    o.line("return out + \"\\\"\";");
    o.close("}");
    o.open("function bytes(b: Uint8Array): string {");
    o.line("let out = \"b\\\"\";");
    o.line("for (const x of b) out += hex(x, 2);");
    o.line("return out + \"\\\"\";");
    o.close("}");
    o.line("void f64; void str; void bytes;");
    o.blank();
    for d in &schema.defs {
        match d {
            Def::Struct(s) => {
                o.open(&format!("export function dump{}(v: {}, t: Tables): string {{", s.name, s.name));
                o.line("void t;");
                o.line(&format!("return {};", struct_expr(s, schema, "v")));
                o.close("}");
                o.blank();
                if s.columns_used {
                    o.open(&format!("export function dump{}Columns(v: {}[], t: Tables): string {{", s.name, s.name));
                    o.line(&format!("return \"[\" + v.map((e) => dump{}(e, t)).join(\",\") + \"]\";", s.name));
                    o.close("}");
                    o.blank();
                }
            }
            Def::Enum(e) => enum_dump(schema, &mut o, e),
        }
    }
    o.open("export function dumpTables(t: Tables): string {");
    if schema.tables.is_empty() {
        o.line("void t;");
    }
    o.line("let out = \"\";");
    for (i, tb) in schema.tables.iter().enumerate() {
        let p = table_prop(schema, i);
        match tb.entry {
            None => o.line(&format!("out += \"{}=[\" + t.{p}.list.map((e) => str(e)).join(\",\") + \"];\";", tb.name)),
            Some(e) => {
                o.line(&format!("out += \"{}=[\" + t.{p}.map((e) => dump{}(e, t)).join(\",\") + \"];\";", tb.name, schema.def(e).name()))
            }
        }
    }
    o.line("return out;");
    o.close("}");
    o.finish()
}

fn enum_dump(schema: &Schema, o: &mut Out, e: &EnumDef) {
    o.open(&format!("export function dump{}(v: {}, t: Tables): string {{", e.name, e.name));
    o.line("void t;");
    if e.unit_only {
        o.open("switch (v) {");
        for v in &e.variants {
            o.line(&format!("case \"{}\": return \"{}\";", v.ts_name, v.name));
        }
        o.close("}");
    } else {
        o.open(&format!("switch (v.{}) {{", e.tag));
        for v in &e.variants {
            o.open(&format!("case \"{}\":", v.ts_name));
            match &v.payload {
                None => o.line(&format!("return \"{}\";", v.name)),
                Some(Ty::Named(n)) if matches!(schema.def(*n), Def::Struct(_)) => {
                    o.line(&format!("return \"{}(\" + dump{}(v, t) + \")\";", v.name, schema.def(*n).name()));
                }
                Some(ty) => o.line(&format!("return \"{}(\" + {} + \")\";", v.name, dump_expr(schema, ty, "v.v", 0))),
            }
            o.close("");
        }
        o.close("}");
    }
    o.close("}");
    o.blank();
}
