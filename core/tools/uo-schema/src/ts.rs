//! The TypeScript emitter. Decoded values are plain objects with the camelCase names of the IDL
//! (or its `ts "..."` overrides), `sym` fields are strings, optional fields are absent properties
//! and `columns` are arrays of objects. Erasable syntax only (Node strips the types).

use crate::model::{Def, EnumDef, Schema, StructDef, Ty, camel, ts_acc, ts_key};
use crate::out::{Out, screaming};

pub(crate) fn ts_ty(schema: &Schema, ty: &Ty) -> String {
    match ty {
        Ty::Bool => "boolean".into(),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::I32 | Ty::F64 | Ty::BytesRef | Ty::Ref(_) => "number".into(),
        Ty::Utf16 | Ty::Sym => "string".into(),
        Ty::Bytes => "Uint8Array".into(),
        Ty::Named(i) => schema.def(*i).name().to_string(),
        Ty::List(inner) => match **inner {
            Ty::U8 => "Uint8Array".into(),
            _ => format!("{}[]", ts_ty(schema, inner)),
        },
        Ty::Columns(i) => format!("{}[]", schema.def(*i).name()),
    }
}

pub(crate) fn table_prop(schema: &Schema, t: usize) -> String {
    camel(&schema.tables[t].name)
}

fn enc(schema: &Schema, o: &mut Out, ty: &Ty, x: &str, depth: usize) {
    match ty {
        Ty::Bool => o.line(&format!("w.bool({x});")),
        Ty::U8 => o.line(&format!("w.u8({x});")),
        Ty::U16 => o.line(&format!("w.u16({x});")),
        Ty::U32 | Ty::BytesRef | Ty::Ref(_) => o.line(&format!("w.u32({x});")),
        Ty::I32 => o.line(&format!("w.i32({x});")),
        Ty::F64 => o.line(&format!("w.f64({x});")),
        Ty::Utf16 => o.line(&format!("w.utf16({x});")),
        Ty::Sym => o.line(&format!("w.u32(t.sym.intern({x}));")),
        Ty::Bytes => o.line(&format!("w.bytes({x});")),
        Ty::Named(i) => o.line(&format!("write{}(w, {x}, t);", schema.def(*i).name())),
        Ty::Columns(i) => o.line(&format!("write{}Columns(w, {x}, t);", schema.def(*i).name())),
        Ty::List(inner) => match **inner {
            Ty::Bool => o.line(&format!("w.bitList({x});")),
            Ty::U8 => o.line(&format!("w.bytes({x});")),
            _ => {
                o.line(&format!("w.len({x}.length);"));
                let e = format!("e{depth}");
                o.open(&format!("for (const {e} of {x}) {{"));
                enc(schema, o, inner, &e, depth + 1);
                o.close("}");
            }
        },
    }
}

fn dec(schema: &Schema, ty: &Ty) -> String {
    match ty {
        Ty::Bool => "r.bool()".into(),
        Ty::U8 => "r.u8()".into(),
        Ty::U16 => "r.u16()".into(),
        Ty::U32 | Ty::BytesRef => "r.u32()".into(),
        Ty::I32 => "r.i32()".into(),
        Ty::F64 => "r.f64()".into(),
        Ty::Utf16 => "r.utf16()".into(),
        Ty::Bytes => "r.bytes()".into(),
        Ty::Sym => "t.sym.list[r.ref(0, \"sym\")]!".into(),
        Ty::Ref(i) => format!("r.ref({i}, \"{}\")", schema.tables[*i].name),
        Ty::Named(i) => format!("read{}(r, t)", schema.def(*i).name()),
        Ty::Columns(i) => format!("read{}Columns(r, t)", schema.def(*i).name()),
        Ty::List(inner) => match **inner {
            Ty::Bool => "r.bitList()".into(),
            Ty::U8 => "r.bytes()".into(),
            _ => format!("r.list({}, () => {})", schema.list_elem_min_bits(inner), dec(schema, inner)),
        },
    }
}

fn byte_array(b: &[u8]) -> String {
    format!("new Uint8Array([{}])", b.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", "))
}

pub fn emit(schema: &Schema, source: &str, runtime_import: &str) -> String {
    let mut o = Out::new("  ");
    o.line(&format!(
        "// @generated by core/tools/uo-schema from {source} (schema `{}`, hash {}). Do not edit: change the .uos file and run `cargo run -p uo-schema -- generate`.",
        schema.name,
        schema.hash_hex()
    ));
    o.line("// Erasable TypeScript only; plain objects with the camelCase names of the IDL.");
    o.blank();
    // `tagIndex` writes the tag of a unit-only enum: a schema without one must not import it (noUnusedLocals)
    let tag_index = if schema.defs.iter().any(|d| matches!(d, Def::Enum(e) if e.unit_only)) { "tagIndex, " } else { "" };
    o.line(&format!("import {{ DEFAULT_LIMITS, DecodeError, EncodeError, Reader, SymTable, Writer, bitAt, {tag_index}type Limits }} from \"{runtime_import}\";"));
    o.line("export { DEFAULT_LIMITS, DecodeError, EncodeError, SymTable, type Limits };");
    o.blank();
    o.line(&format!("export const NAME = \"{}\";", schema.name));
    o.line(&format!("export const MAGIC = {};", byte_array(&schema.magic)));
    o.line(&format!("export const SCHEMA_HASH = {};", byte_array(&schema.hash)));
    for (id, m) in schema.messages.iter().enumerate() {
        o.line(&format!("export const MSG_{} = {id};", screaming(schema.def(*m).name())));
    }
    o.blank();
    for d in &schema.defs {
        match d {
            Def::Struct(s) => {
                emit_struct(schema, &mut o, s);
                if s.columns_used {
                    emit_columns(schema, &mut o, s);
                }
            }
            Def::Enum(e) => emit_enum(schema, &mut o, e),
        }
    }
    emit_tables(schema, &mut o);
    for m in &schema.messages {
        emit_message(schema, &mut o, schema.struct_def(*m));
    }
    o.finish()
}

fn emit_struct(schema: &Schema, o: &mut Out, s: &StructDef) {
    o.line("/**");
    for d in &s.doc {
        o.line(&format!(" * {d}"));
    }
    o.line(" */");
    o.open(&format!("export interface {} {{", s.name));
    for f in &s.fields {
        o.docs("/** ", &f.doc.iter().map(|d| format!("{d} */")).collect::<Vec<_>>());
        let opt = if f.optional || f.ty == Ty::Bool { "?" } else { "" };
        o.line(&format!("{}{opt}: {};", ts_key(&f.ts_name), ts_ty(schema, &f.ty)));
    }
    o.close("}");
    o.blank();
    o.open(&format!("export function write{}(w: Writer, v: {}, t: Tables): void {{", s.name, s.name));
    o.line("void t;");
    let bits: Vec<String> = s
        .fields
        .iter()
        .filter(|f| f.is_bit())
        .map(|f| if f.optional { format!("v{} !== undefined", ts_acc(&f.ts_name)) } else { format!("!!v{}", ts_acc(&f.ts_name)) })
        .collect();
    if !bits.is_empty() {
        o.line(&format!("w.bitmap([{}]);", bits.join(", ")));
    }
    for f in &s.fields {
        let x = format!("v{}", ts_acc(&f.ts_name));
        if f.optional {
            o.open(&format!("if ({x} !== undefined) {{"));
            enc(schema, o, &f.ty, &x, 0);
            o.close("}");
        } else if f.ty != Ty::Bool {
            enc(schema, o, &f.ty, &x, 0);
        }
    }
    o.close("}");
    o.blank();
    o.open(&format!("export function read{}(r: Reader, t: Tables): {} {{", s.name, s.name));
    o.line("void t;");
    if s.recursive {
        o.line("r.enter();");
    }
    let nbits = s.bit_fields();
    if nbits > 0 {
        o.line(&format!("const bm = r.bitmap({nbits});"));
    }
    let mut bit_i = 0usize;
    for f in &s.fields {
        if f.optional {
            o.line(&format!("let f_{}: {} | undefined;", f.name, ts_ty(schema, &f.ty)));
            o.line(&format!("if (bitAt(bm, {bit_i})) f_{} = {};", f.name, dec(schema, &f.ty)));
            bit_i += 1;
        } else if f.ty == Ty::Bool {
            o.line(&format!("const f_{} = bitAt(bm, {bit_i});", f.name));
            bit_i += 1;
        } else {
            o.line(&format!("const f_{} = {};", f.name, dec(schema, &f.ty)));
        }
    }
    if s.recursive {
        o.line("r.leave();");
    }
    let init: Vec<String> = s.fields.iter().filter(|f| !f.optional).map(|f| format!("{}: f_{}", ts_key(&f.ts_name), f.name)).collect();
    o.line(&format!("const o: {} = {{ {} }};", s.name, init.join(", ")));
    for f in s.fields.iter().filter(|f| f.optional) {
        o.line(&format!("if (f_{} !== undefined) o{} = f_{};", f.name, ts_acc(&f.ts_name), f.name));
    }
    o.line("return o;");
    o.close("}");
    o.blank();
}

fn emit_columns(schema: &Schema, o: &mut Out, s: &StructDef) {
    o.open(&format!("export function write{}Columns(w: Writer, v: {}[], t: Tables): void {{", s.name, s.name));
    o.line("void t;");
    o.line("w.len(v.length);");
    for f in &s.fields {
        let x = format!("e0{}", ts_acc(&f.ts_name));
        if f.optional {
            o.line(&format!("w.bits(v.length, (i) => v[i]!{} !== undefined);", ts_acc(&f.ts_name)));
            o.open("for (const e0 of v) {");
            o.open(&format!("if ({x} !== undefined) {{"));
            enc(schema, o, &f.ty, &x, 1);
            o.close("}");
            o.close("}");
        } else if f.ty == Ty::Bool {
            o.line(&format!("w.bits(v.length, (i) => !!v[i]!{});", ts_acc(&f.ts_name)));
        } else {
            o.open("for (const e0 of v) {");
            enc(schema, o, &f.ty, &x, 1);
            o.close("}");
        }
    }
    o.close("}");
    o.blank();
    o.open(&format!("export function read{}Columns(r: Reader, t: Tables): {}[] {{", s.name, s.name));
    o.line("void t;");
    o.line(&format!("const n = r.listLen({});", s.columns_min_bits));
    o.line(&format!("const out: {}[] = [];", s.name));
    o.line(&format!("for (let i = 0; i < n; i++) out.push({{}} as {});", s.name));
    for f in &s.fields {
        if f.optional {
            o.line(&format!("const present_{} = r.bits(n);", f.name));
            o.open("for (let i = 0; i < n; i++) {");
            o.line(&format!("if (bitAt(present_{}, i)) out[i]!{} = {};", f.name, ts_acc(&f.ts_name), dec(schema, &f.ty)));
            o.close("}");
        } else if f.ty == Ty::Bool {
            o.line(&format!("const flags_{} = r.bits(n);", f.name));
            o.line(&format!("for (let i = 0; i < n; i++) out[i]!{} = bitAt(flags_{}, i);", ts_acc(&f.ts_name), f.name));
        } else {
            o.line(&format!("for (let i = 0; i < n; i++) out[i]!{} = {};", ts_acc(&f.ts_name), dec(schema, &f.ty)));
        }
    }
    o.line("return out;");
    o.close("}");
    o.blank();
}

fn emit_enum(schema: &Schema, o: &mut Out, e: &EnumDef) {
    for d in &e.doc {
        o.line(&format!("/** {d} */"));
    }
    if e.unit_only {
        let tags: Vec<String> = e.variants.iter().map(|v| format!("\"{}\"", v.ts_name)).collect();
        o.line(&format!("export type {} = {};", e.name, tags.join(" | ")));
        let k = screaming(&e.name);
        o.line(&format!("const {k}_TAGS = [{}] as const;", tags.join(", ")));
        o.line(&format!("const {k}_INDEX = new Map<string, number>({k}_TAGS.map((s, i): [string, number] => [s, i]));"));
        o.blank();
        o.open(&format!("export function write{}(w: Writer, v: {}, t: Tables): void {{", e.name, e.name));
        o.line("void t;");
        o.line(&format!("w.u32(tagIndex(\"{}\", {k}_INDEX, v));", e.name));
        o.close("}");
        o.blank();
        o.open(&format!("export function read{}(r: Reader, t: Tables): {} {{", e.name, e.name));
        o.line("void t;");
        o.line(&format!("return {k}_TAGS[r.tag(\"{}\", {k}_TAGS.length)]!;", e.name));
        o.close("}");
        o.blank();
        return;
    }
    o.open(&format!("export type {} =", e.name));
    for (i, v) in e.variants.iter().enumerate() {
        let last = i + 1 == e.variants.len();
        let end = if last { ";" } else { "" };
        let ty = match &v.payload {
            None => format!("| {{ {}: \"{}\" }}", e.tag, v.ts_name),
            Some(Ty::Named(n)) if matches!(schema.def(*n), Def::Struct(_)) => {
                format!("| ({{ {}: \"{}\" }} & {})", e.tag, v.ts_name, schema.def(*n).name())
            }
            Some(t) => format!("| {{ {}: \"{}\"; v: {} }}", e.tag, v.ts_name, ts_ty(schema, t)),
        };
        o.line(&format!("{ty}{end}"));
    }
    o.close("");
    o.blank();
    o.open(&format!("export function write{}(w: Writer, v: {}, t: Tables): void {{", e.name, e.name));
    o.line("void t;");
    o.open(&format!("switch (v.{}) {{", e.tag));
    for (i, v) in e.variants.iter().enumerate() {
        o.open(&format!("case \"{}\":", v.ts_name));
        o.line(&format!("w.u32({i});"));
        match &v.payload {
            None => {}
            Some(Ty::Named(n)) if matches!(schema.def(*n), Def::Struct(_)) => {
                o.line(&format!("write{}(w, v, t);", schema.def(*n).name()));
            }
            Some(ty) => enc(schema, o, ty, "v.v", 0),
        }
        o.line("break;");
        o.close("");
    }
    o.open("default:");
    o.line(&format!("throw new EncodeError(`\"${{String((v as {{ {}: string }}).{})}}\" is not a variant of {}`);", e.tag, e.tag, e.name));
    o.close("");
    o.close("}");
    o.close("}");
    o.blank();
    o.open(&format!("export function read{}(r: Reader, t: Tables): {} {{", e.name, e.name));
    o.line("void t;");
    if e.recursive {
        o.line("r.enter();");
    }
    o.line("const tag = r.u32();");
    o.line(&format!("let out: {};", e.name));
    o.open("switch (tag) {");
    for (i, v) in e.variants.iter().enumerate() {
        o.open(&format!("case {i}:"));
        match &v.payload {
            None => o.line(&format!("out = {{ {}: \"{}\" }};", e.tag, v.ts_name)),
            Some(Ty::Named(n)) if matches!(schema.def(*n), Def::Struct(_)) => {
                o.line(&format!("out = Object.assign(read{}(r, t), {{ {}: \"{}\" as const }});", schema.def(*n).name(), e.tag, v.ts_name));
            }
            Some(ty) => o.line(&format!("out = {{ {}: \"{}\", v: {} }};", e.tag, v.ts_name, dec(schema, ty))),
        }
        o.line("break;");
        o.close("");
    }
    o.open("default:");
    o.line(&format!("throw new DecodeError(\"BadTag\", `${{tag}} is not a variant of {}`);", e.name));
    o.close("");
    o.close("}");
    if e.recursive {
        o.line("r.leave();");
    }
    o.line("return out;");
    o.close("}");
    o.blank();
}

fn emit_tables(schema: &Schema, o: &mut Out) {
    let entry_ty = |t: &crate::model::Table| match t.entry {
        None => "SymTable".to_string(),
        Some(e) => format!("{}[]", schema.def(e).name()),
    };
    o.line("/** What a decoder has received so far in one generation, and what an encoder keeps: the entries of every table (ids are positions). */");
    o.open("export interface Tables {");
    o.line("generation: number | undefined;");
    for (i, t) in schema.tables.iter().enumerate() {
        o.line(&format!("{}: {};", table_prop(schema, i), entry_ty(t)));
    }
    o.close("}");
    o.blank();
    o.open("export function newTables(): Tables {");
    let inits: Vec<String> = schema
        .tables
        .iter()
        .enumerate()
        .map(|(i, t)| format!("{}: {}", table_prop(schema, i), if t.entry.is_none() { "new SymTable()" } else { "[]" }))
        .collect();
    let mut all = vec!["generation: undefined".to_string()];
    all.extend(inits);
    o.line(&format!("return {{ {} }};", all.join(", ")));
    o.close("}");
    o.blank();
    o.line("/** The number of entries of every table, in declaration order. */");
    o.open("export function tableLens(t: Tables): number[] {");
    if schema.tables.is_empty() {
        o.line("void t;");
    }
    let lens: Vec<String> = (0..schema.tables.len()).map(|i| format!("t.{}.length", table_prop(schema, i))).collect();
    o.line(&format!("return [{}];", lens.join(", ")));
    o.close("}");
    o.blank();
    o.line(
        "/** The encoder's state: the tables (symbols are interned into them), how much of each was already sent, and the generation. */",
    );
    o.open("export interface EncodeState {");
    o.line("generation: number;");
    o.line("tables: Tables;");
    o.line("/** Per table, the entries before this index were sent by earlier messages. */");
    o.line("sent: number[];");
    o.close("}");
    o.blank();
    o.open("export function newEncodeState(generation: number, tables: Tables = newTables()): EncodeState {");
    o.line(&format!("return {{ generation, tables, sent: new Array<number>({}).fill(0) }};", schema.tables.len()));
    o.close("}");
    o.blank();
}

fn emit_message(schema: &Schema, o: &mut Out, m: &StructDef) {
    let name = &m.name;
    let konst = format!("MSG_{}", screaming(name));
    o.line(&format!("/** Reads a `{name}` message. `tables` is the state of this stream of messages: the new entries are appended, a new generation replaces them, and an error leaves them as they were. */"));
    o.open(&format!("export function decode{name}(buf: Uint8Array, tables: Tables, limits: Limits = DEFAULT_LIMITS): {name} {{"));
    o.line("const r = new Reader(buf, limits);");
    o.line("const head = r.header(MAGIC, SCHEMA_HASH);");
    o.line(&format!(
        "if (head.message !== {konst}) throw new DecodeError(\"WrongMessage\", `message id ${{head.message}}, expected ${{{konst}}}`);"
    ));
    let props: Vec<String> = (0..schema.tables.len()).map(|i| table_prop(schema, i)).collect();
    o.line("const reset = tables.generation !== head.generation;");
    let mut saved: Vec<String> = vec!["generation: tables.generation".to_string()];
    saved.extend(props.iter().map(|p| format!("{p}: tables.{p}")));
    o.line(&format!("const saved = reset ? {{ {} }} : undefined;", saved.join(", ")));
    o.line("if (reset) Object.assign(tables, newTables());");
    if !schema.tables.is_empty() {
        o.line("const lens = tableLens(tables);");
    }
    o.open("try {");
    for (i, t) in schema.tables.iter().enumerate() {
        let p = &props[i];
        o.line(&format!("const n_{p} = r.tableHeader({i}, \"{}\", tables.{p}.length, {});", t.name, t.min_bits));
    }
    for (i, t) in schema.tables.iter().enumerate() {
        let p = &props[i];
        match t.entry {
            None => o.line(&format!("for (let i = 0; i < n_{p}; i++) tables.{p}.push(r.utf16());")),
            Some(e) => o.line(&format!("for (let i = 0; i < n_{p}; i++) tables.{p}.push(read{}(r, tables));", schema.def(e).name())),
        }
    }
    o.line(&format!("const msg = read{name}(r, tables);"));
    o.line("r.end();");
    o.line("tables.generation = head.generation;");
    o.line("return msg;");
    o.mid("} catch (e) {");
    o.open("if (saved) {");
    o.line("Object.assign(tables, saved);");
    if schema.tables.is_empty() {
        o.close("}");
    } else {
        o.mid("} else {");
        for (i, t) in schema.tables.iter().enumerate() {
            let p = &props[i];
            if t.entry.is_none() {
                o.line(&format!("tables.{p}.truncate(lens[{i}]!);"));
            } else {
                o.line(&format!("tables.{p}.length = lens[{i}]!;"));
            }
        }
        o.close("}");
    }
    o.line("throw e;");
    o.close("}");
    o.close("}");
    o.blank();
    o.line(&format!("/** Writes a `{name}` message: the header, the new entries of every table (those past `state.sent`), the body. Symbols are interned into `state.tables`. */"));
    o.open(&format!("export function encode{name}(msg: {name}, state: EncodeState): Uint8Array {{"));
    o.line("const t = state.tables;");
    o.line("const entries = new Writer();");
    for (i, tb) in schema.tables.iter().enumerate() {
        if let Some(e) = tb.entry {
            let p = &props[i];
            o.line(&format!("for (let i = state.sent[{i}]!; i < t.{p}.length; i++) write{}(entries, t.{p}[i]!, t);", schema.def(e).name()));
        }
    }
    o.line("const body = new Writer();");
    o.line(&format!("write{name}(body, msg, t);"));
    o.line("const w = new Writer();");
    o.line(&format!("w.header(MAGIC, SCHEMA_HASH, {konst}, state.generation);"));
    for (i, _) in schema.tables.iter().enumerate() {
        let p = &props[i];
        o.line(&format!("w.u32(state.sent[{i}]!);"));
        o.line(&format!("w.len(t.{p}.length - state.sent[{i}]!);"));
    }
    for (i, tb) in schema.tables.iter().enumerate() {
        if tb.entry.is_none() {
            let p = &props[i];
            o.line(&format!("for (let i = state.sent[{i}]!; i < t.{p}.length; i++) w.utf16(t.{p}.list[i]!);"));
        }
    }
    o.line("w.raw(entries);");
    o.line("w.raw(body);");
    o.line("state.sent = tableLens(t);");
    o.line("return w.finish();");
    o.close("}");
    o.blank();
}
