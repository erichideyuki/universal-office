// Generates core/crates/uo-calc/src/fn_table.rs (frontier A2, record core/docs/modules/uo-calc.md "A2"): the
// metadata of every function the frozen TS registers (`fn.ts` REGISTRY, filled by `functions/*.ts` at load) and
// the file prefix of every Excel catalogue function (`i18n/catalog-data.ts`), merged into one table sorted by
// name. The printer reads the prefix (`print.ts`: `n.prefix ?? catalogEntry(name)?.prefix ?? lookupFn(name)?.prefix`),
// the evaluator the registry part (argument modes per position, lift, volatile, returnsRef, acceptsErrors,
// min/max arguments). The function BODIES are frontier A4 (`functions::body`).
//
//   node core/crates/uo-calc/js/gen-fn-table.mjs          # rewrites src/fn_table.rs
//   node core/crates/uo-calc/js/gen-fn-table.mjs --check  # fails when the committed file differs
//
// `args` may be a function of the position in the TS; it is sampled for positions 0..PROBE and stored as a fixed
// prefix + a repeating cycle (the shortest description that reproduces every sampled position; positions past
// PROBE follow the cycle, which the TS functions do: they test `i === k`, `i < k`, `i % 2`, `i >= k`).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const C = await import('./lib/common.mjs');

const a = C.args();
const root = C.tsRoot(a);
const base = join(root, 'sheet', 'packages', 'calc', 'dist');
const imp = (p) => import(pathToFileURL(join(base, p)).href);
const calc = await imp('index.js');
const data = await imp('i18n/catalog-data.js');

const PROBE = 600;
const MODES = ['value', 'array', 'ref', 'any', 'lazy'];

/** Shortest (prefix, cycle) with modes[i] = cycle[(i - prefix.length) % cycle.length] past the prefix. */
function compress(modes) {
  let best;
  for (let p = 0; p < 300 && p < modes.length; p++) {
    for (let k = 1; k <= 8; k++) {
      let ok = true;
      for (let i = p; i < modes.length && ok; i++) ok = modes[i] === modes[p + ((i - p) % k)];
      if (ok && (!best || p + k < best.p + best.k)) best = { p, k };
    }
  }
  if (!best) throw new Error(`no (prefix, cycle) for ${modes.slice(0, 50).join(',')}`);
  return { prefix: modes.slice(0, best.p), cycle: modes.slice(best.p, best.p + best.k) };
}

const entries = new Map();
for (const [name, , p] of data.SHEET_FUNCTIONS) entries.set(name, { name, cat: data.FILE_PREFIXES[p] ?? '' });
const extraPrefixes = new Set();
for (const d of calc.allFns()) {
  const key = d.name.toUpperCase();
  const e = entries.get(key) ?? { name: key };
  const modes = [];
  for (let i = 0; i < PROBE; i++) {
    const m = typeof d.args === 'function' ? d.args(i) : d.args;
    if (!MODES.includes(m)) throw new Error(`${key}: mode ${m} at ${i}`);
    modes.push(m);
  }
  if (d.prefix !== undefined && !['_xlfn.', '_xlfn._xlws.', '_xlws.', ''].includes(d.prefix)) extraPrefixes.add(d.prefix);
  e.def = {
    prefix: d.prefix,
    min: d.minArgs,
    max: d.maxArgs,
    ...((c) => ({ fixed: c.prefix, cycle: c.cycle }))(compress(modes)),
    lift: !!d.lift, volatile: !!d.volatile, returnsRef: !!d.returnsRef, acceptsErrors: !!d.acceptsErrors,
    // the TS keeps the name as registered (REGISTRY key = upper case); FnDef.name is what `lookupFn` returns
    defName: d.name,
  };
  entries.set(key, e);
}
if (extraPrefixes.size) throw new Error(`unexpected registry prefixes: ${[...extraPrefixes]}`);
for (const e of entries.values()) if (/[^\x20-\x7e]/.test(e.name)) throw new Error(`non-ASCII function name ${e.name}`);

// sorted by UTF-16 code units (= bytes: ASCII names), the order of the binary search
const sorted = [...entries.values()].sort((x, y) => (x.name < y.name ? -1 : x.name > y.name ? 1 : 0));
const cat = (e) => (e.cat === undefined ? 'CatPrefix::None' : e.cat === '' ? 'CatPrefix::Empty' : e.cat === '_xlfn.' ? 'CatPrefix::Xlfn' : 'CatPrefix::XlfnXlws');
const pre = (p) => (p === undefined ? 'None' : `Some(${JSON.stringify(p)})`);
const modeList = (ms) => `&[${ms.map((m) => `M::${m[0].toUpperCase()}${m.slice(1)}`).join(', ')}]`;
let defs = 0;
const lines = [];
for (const e of sorted) {
  const d = e.def;
  let def = 'None';
  if (d) {
    defs++;
    const flags = [d.lift && 'LIFT', d.volatile && 'VOLATILE', d.returnsRef && 'RETURNS_REF', d.acceptsErrors && 'ACCEPTS_ERRORS'].filter(Boolean);
    def = `Some(FnMeta { prefix: ${pre(d.prefix)}, min_args: ${d.min}, max_args: ${d.max}, fixed: ${modeList(d.fixed)}, cycle: ${modeList(d.cycle)}, flags: ${flags.length ? flags.map((f) => `F::${f}`).join(' | ') : '0'} })`;
    if (d.defName !== e.name) throw new Error(`registered name ${d.defName} differs from its key ${e.name}`);
  }
  lines.push(`    FnEntry { name: ${JSON.stringify(e.name)}, catalog: ${cat(e)}, def: ${def} },`);
}

const out = `// GENERATED by core/crates/uo-calc/js/gen-fn-table.mjs from the frozen TS (fn.ts registry + i18n/catalog-data.ts,
// Excel ${data.EXCEL_BUILD}) — do not edit by hand. ${sorted.length} names, ${defs} registered functions.
//! The merged function table (frontier A2): one row per name, sorted by name.

use crate::fnreg::{ArgMode as M, CatPrefix, FnEntry, FnFlags as F, FnMeta};

/// Every catalogue or registered function name, sorted by UTF-16 code unit (all ASCII).
#[rustfmt::skip]
pub static FN_TABLE: [FnEntry; ${sorted.length}] = [
${lines.join('\n')}
];
`;
const target = join(C.crateDir, 'src', 'fn_table.rs');
if (a.flag('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== out) throw new Error('src/fn_table.rs is stale: rerun gen-fn-table.mjs');
  console.log('fn_table.rs up to date');
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}: ${sorted.length} names, ${defs} registered`);
}
