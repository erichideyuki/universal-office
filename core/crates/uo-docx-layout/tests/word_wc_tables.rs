#[derive(Clone, Debug)]
struct Line {
    y: f64,
    x0: f64,
    x1: f64,
    text: String,
}

/// A straight rule: `vertical` = along y (`c` = x of its centre), else along x (`c` = y); `t` = thickness; `a..b` = extent.
#[derive(Clone, Copy, Debug)]
struct Rule {
    vertical: bool,
    c: f64,
    t: f64,
    a: f64,
    b: f64,
}

#[derive(Debug, Default)]
struct Doc {
    pages: Vec<Vec<Line>>,
    rules: Vec<Vec<Rule>>,
}

/// `normChar` (oracle-compare.ts).
fn norm_char(cp: u32) -> String {
    const PUA: [u32; 9] = [0xf0b7, 0xf0a7, 0xf0d8, 0xf0fc, 0xf076, 0xf0a8, 0xf06e, 0xf0e0, 0xf0a1];
    const BUL: [u32; 19] = [
        0x2022, 0x25aa, 0x25cf, 0x25e6, 0x2023, 0x2043, 0x25a0, 0x25a1, 0x2219, 0x00b7, 0x27a2, 0x2713, 0x2714, 0x25c6, 0x25c7, 0x2756,
        0x00a7, 0x2192, 0x27a4,
    ];
    if PUA.contains(&cp) || BUL.contains(&cp) || (0xf020..=0xf0ff).contains(&cp) {
        return "•".into();
    }
    match cp {
        0xa0 | 0x2007 | 0x202f => " ".into(),
        0xad => String::new(),
        0x2010..=0x2014 | 0x2212 => "-".into(),
        0x2018 | 0x2019 | 0x201a | 0x2032 => "'".into(),
        0x201c | 0x201d | 0x201e | 0x2033 => "\"".into(),
        0x2026 => "...".into(),
        0xfb01 => "fi".into(),
        0xfb02 => "fl".into(),
        _ => char::from_u32(cp).map(String::from).unwrap_or_default(),
    }
}

/// `engineLines(res, skipRotated = false)` and the page's border rules.
fn engine_lines(l: &Layout) -> Doc {
    let mut pages = Vec::new();
    let mut rules = Vec::new();
    for lp in &l.pages {
        let page = &lp.page;
        let cols = &page.list.glyphs;
        let mut lines: Vec<Line> = Vec::new();
        let mut last_cp: Vec<u32> = Vec::new();
        let mut cur: Option<usize> = None;
        let mut rs = Vec::new();
        for it in &page.list.items {
            match it {
                Item::Line { x1, y1, x2, y2, width_pt, .. } => {
                    let (x1, y1, x2, y2) = (*x1 / 20.0, *y1 / 20.0, *x2 / 20.0, *y2 / 20.0);
                    if (x1 - x2).abs() < 0.01 && (y1 - y2).abs() > 0.01 {
                        rs.push(Rule { vertical: true, c: x1, t: *width_pt, a: jm::min(y1, y2), b: jm::max(y1, y2) });
                    } else if (y1 - y2).abs() < 0.01 && (x1 - x2).abs() > 0.01 {
                        rs.push(Rule { vertical: false, c: y1, t: *width_pt, a: jm::min(x1, x2), b: jm::max(x1, x2) });
                    }
                }
                Item::Rect { x, y, w, h, .. } => {
                    let (x, y, w, h) = (*x / 20.0, *y / 20.0, *w / 20.0, *h / 20.0);
                    if w < 4.0 && h > 4.0 {
                        rs.push(Rule { vertical: true, c: x + w / 2.0, t: w, a: y, b: y + h });
                    } else if h < 4.0 && w > 4.0 {
                        rs.push(Rule { vertical: false, c: y + h / 2.0, t: h, a: x, b: x + w });
                    }
                }
                Item::Glyphs { size_pt, y, glyphs, flags, .. } => {
                    if flags.0 & RunFlags::AS_PATH != 0 {
                        continue;
                    }
                    let y = *y / 20.0;
                    let s = glyphs.start as usize;
                    for k in s..s + glyphs.len as usize {
                        let cp = cols.cp[k];
                        let ch = norm_char(cp);
                        if ch.is_empty() || ch.chars().all(uo_jsnum::text::is_js_space) || cp > 0xffff {
                            continue;
                        }
                        let x = cols.x[k] / 20.0;
                        let size = jm::round(*size_pt / 0.12) * 0.12;
                        let tol = jm::max(1.0, 0.3 * size);
                        let right = x + jm::max(1.0, 0.5 * size);
                        match cur {
                            Some(c) if (y - lines[c].y).abs() <= tol && x >= lines[c].x1 - tol * 2.0 => {
                                lines[c].text.push_str(&ch);
                                lines[c].x1 = jm::max(lines[c].x1, right);
                            }
                            _ => {
                                lines.push(Line { y, x0: x, x1: right, text: ch });
                                cur = Some(lines.len() - 1);
                            }
                        }
                        let n = lines.len();
                        if last_cp.len() < n {
                            last_cp.resize(n, 0);
                        }
                        last_cp[n - 1] = cp;
                    }
                }
                _ => {}
            }
        }
        // pdfium's hyphen at the end of a line after a LETTER drops when the next line starts with a letter or digit
        for k in 0..lines.len().saturating_sub(1) {
            let t: Vec<char> = lines[k].text.chars().collect();
            let next_ok = lines[k + 1].text.chars().next().is_some_and(|c| c.is_alphabetic() || c.is_ascii_digit());
            if t.len() > 1 && t[t.len() - 1] == '-' && last_cp[k] == 0x2d && t[t.len() - 2].is_alphabetic() && next_ok {
                lines[k].text.pop();
            }
        }
        pages.push(lines);
        rules.push(join_rules(rs));
    }
    Doc { pages, rules }
}

/// Collinear pieces of the same thickness that touch become one rule (a gap up to twice the thicker of the rule and
/// the crossing borders: Word cuts a border at every cell corner); sorted.
fn join_rules(mut rs: Vec<Rule>) -> Vec<Rule> {
    let cross = |vertical: bool| rs.iter().filter(|r| r.vertical != vertical).fold(0.0, |a, r| jm::max(a, r.t));
    let (cross_v, cross_h) = (cross(true), cross(false));
    rs.sort_by(|p, q| {
        (p.vertical, jm::round(p.c * 10.0), jm::round(p.t * 100.0), p.a)
            .partial_cmp(&(q.vertical, jm::round(q.c * 10.0), jm::round(q.t * 100.0), q.a))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    let mut out: Vec<Rule> = Vec::new();
    for r in rs {
        if let Some(l) = out.last_mut()
            && l.vertical == r.vertical
            && (l.c - r.c).abs() <= 0.11
            && (l.t - r.t).abs() <= 0.06
            && r.a <= l.b + 0.6 + 2.0 * jm::max(r.t, if r.vertical { cross_v } else { cross_h })
        {
            l.b = jm::max(l.b, r.b);
            continue;
        }
        out.push(r);
    }
    out
}

fn word_lines(json: &str) -> Doc {
    use uo_docx::js::JsonValue;
    let obj = |v: &JsonValue, k: &str| -> JsonValue {
        let JsonValue::Object(o) = v else { panic!("object") };
        o.get(k).cloned().unwrap_or_default()
    };
    let arr = |v: JsonValue| -> Vec<JsonValue> {
        match v {
            JsonValue::Array(a) => a,
            _ => Vec::new(),
        }
    };
    let num = |v: JsonValue| -> f64 {
        let JsonValue::Num(x) = v else { panic!("number") };
        x
    };
    let text = |v: JsonValue| match v {
        JsonValue::Str(s) => String::from_utf16_lossy(s.units()),
        _ => String::new(),
    };
    let v = uo_docx::read::json_parse::parse(json).expect("word.json");
    let mut doc = Doc::default();
    for p in arr(obj(&v, "pages")) {
        doc.pages.push(
            arr(obj(&p, "lines"))
                .iter()
                .map(|l| Line { y: num(obj(l, "y")), x0: num(obj(l, "x0")), x1: num(obj(l, "x1")), text: text(obj(l, "text")) })
                .collect(),
        );
        let mut rs = Vec::new();
        for o in arr(obj(&p, "objs")) {
            if text(obj(&o, "t")) != "path" {
                continue;
            }
            let (x0, y0, x1, y1) = (num(obj(&o, "x0")), num(obj(&o, "y0")), num(obj(&o, "x1")), num(obj(&o, "y1")));
            let (w, h) = (x1 - x0, y1 - y0);
            if w < 4.0 && h > 4.0 {
                rs.push(Rule { vertical: true, c: (x0 + x1) / 2.0, t: w, a: y0, b: y1 });
            } else if h < 4.0 && w > 4.0 {
                rs.push(Rule { vertical: false, c: (y0 + y1) / 2.0, t: h, a: x0, b: x1 });
            }
        }
        doc.rules.push(join_rules(rs));
    }
    doc
}

/// Tab leaders collapse to three (`([._\-·])\1{2,}` → `$1$1$1`).
fn collapse(t: &str) -> String {
    let c: Vec<char> = t.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    while i < c.len() {
        let ch = c[i];
        let mut j = i;
        while j < c.len() && c[j] == ch {
            j += 1;
        }
        let n = j - i;
        let take = if matches!(ch, '.' | '_' | '-' | '·') && n >= 3 { 3 } else { n };
        out.extend(std::iter::repeat_n(ch, take));
        i = j;
    }
    out
}

#[derive(Debug, Default)]
struct Cmp {
    pages_w: usize,
    pages_o: usize,
    lines_w: usize,
    matched: usize,
    same_page: usize,
    max_dy: f64,
    max_dx: f64,
    first_diff: Option<String>,
    /// the rules comparer: the first rule of Word without a partner in ours (or the reverse)
    rule_diff: Option<String>,
}

/// `compareLines` (LCS on the texts, Δbaseline/Δx on the pairs of the same page) and the rules.
fn compare(word: &Doc, ours: &Doc) -> Cmp {
    let norm = |d: &Doc| -> Vec<(usize, Line)> {
        d.pages.iter().enumerate().flat_map(|(pi, p)| p.iter().map(move |l| (pi, Line { text: collapse(&l.text), ..l.clone() }))).collect()
    };
    let wl = norm(word);
    let ol = norm(ours);
    let (n, m) = (wl.len(), ol.len());
    let mut dp = vec![vec![0u16; m + 1]; n + 1];
    for i in (0..n).rev() {
        for j in (0..m).rev() {
            dp[i][j] = if wl[i].1.text == ol[j].1.text { dp[i + 1][j + 1] + 1 } else { dp[i + 1][j].max(dp[i][j + 1]) };
        }
    }
    let (mut i, mut j) = (0, 0);
    let mut pairs = Vec::new();
    while i < n && j < m {
        if wl[i].1.text == ol[j].1.text {
            pairs.push((i, j));
            i += 1;
            j += 1;
        } else if dp[i + 1][j] >= dp[i][j + 1] {
            i += 1;
        } else {
            j += 1;
        }
    }
    let mut c = Cmp { pages_w: word.pages.len(), pages_o: ours.pages.len(), lines_w: n, matched: pairs.len(), ..Cmp::default() };
    for &(a, b) in &pairs {
        if wl[a].0 != ol[b].0 {
            continue;
        }
        c.same_page += 1;
        c.max_dy = jm::max(c.max_dy, (wl[a].1.y - ol[b].1.y).abs());
        c.max_dx = jm::max(c.max_dx, (wl[a].1.x0 - ol[b].1.x0).abs());
    }
    let matched: std::collections::HashSet<usize> = pairs.iter().map(|p| p.0).collect();
    c.first_diff = (0..n).find(|k| !matched.contains(k)).map(|k| format!("p{} y={:.1} \"{}\"", wl[k].0 + 1, wl[k].1.y, wl[k].1.text));
    if c.first_diff.is_none() {
        c.first_diff = pairs
            .iter()
            .find(|&&(a, b)| wl[a].0 != ol[b].0)
            .map(|&(a, b)| format!("\"{}\" on page {} (Word {})", wl[a].1.text, ol[b].0 + 1, wl[a].0 + 1));
    }
    c.rule_diff = rule_diff(word, ours);
    c
}

/// The first rule without a partner: same page and direction, centre ±0.3, thickness ±0.15, ends ±0.6 pt plus half the
/// thickest rule of the other direction on the page (Word extends a border into the corners).
fn rule_diff(word: &Doc, ours: &Doc) -> Option<String> {
    let np = word.rules.len().max(ours.rules.len());
    for pi in 0..np {
        let (w, o) = (word.rules.get(pi).map_or(&[][..], Vec::as_slice), ours.rules.get(pi).map_or(&[][..], Vec::as_slice));
        let corner = |rs: &[Rule], vertical: bool| rs.iter().filter(|r| r.vertical != vertical).fold(0.0, |a, r| jm::max(a, r.t));
        let same = |p: &Rule, q: &Rule, extra: f64| {
            p.vertical == q.vertical
                && (p.c - q.c).abs() <= 0.3
                && (p.t - q.t).abs() <= 0.15
                && (p.a - q.a).abs() <= 0.6 + extra
                && (p.b - q.b).abs() <= 0.6 + extra
        };
        for (label, xs, ys) in [("Word", w, o), ("ours", o, w)] {
            for r in xs {
                let extra = jm::max(corner(xs, r.vertical), corner(ys, r.vertical));
                if !ys.iter().any(|q| same(r, q, extra)) {
                    return Some(format!(
                        "p{} {label}'s {} at {:.2} w {:.2} from {:.2} to {:.2} has no partner",
                        pi + 1,
                        if r.vertical { "VLINE" } else { "HLINE" },
                        r.c,
                        r.t,
                        r.a,
                        r.b
                    ));
                }
            }
        }
    }
    None
}

// ───────────────────────── the groups ─────────────────────────

struct Group {
    name: &'static str,
    /// Δx tolerance where the group measures the horizontal position
    dx: Option<f64>,
    /// compare the border rules too
    rules: bool,
    /// the cases (file stems) where the frozen TS's rules differ from Word (laid out with `ts_strict()`)
    ts_diverges: &'static [&'static str],
    /// cases where Word does what neither engine does (asserted to still differ)
    open: &'static [&'static str],
}

fn oracle_dir(group: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/oracle_wc").join(group)
}

fn opts() -> LayoutOptions {
    LayoutOptions { clock: Clock { now_ms: 1_768_478_400_000.0, tz: TimeZoneRule::Fixed { offset_min: 0 } }, ..hyph_opts() }
}

fn lay(bytes: &[u8], o: &LayoutOptions) -> Layout {
    let pkg = uo_opc::Package::open(bytes, &Default::default(), &Default::default()).unwrap();
    let doc = read_document(&pkg, &ReadOptions::default()).unwrap();
    let fonts = OpenFonts::at(&common::repo());
    let mut eng = LayoutEngine::with_hyphenation(common::hyph::hyph_registry());
    eng.layout(DocView::new(&doc), &fonts, o).unwrap().clone()
}

fn equal(c: &Cmp, g: &Group) -> bool {
    c.pages_o == c.pages_w
        && c.matched == c.lines_w
        && c.same_page == c.matched
        && c.max_dy <= 0.3
        && g.dx.is_none_or(|t| c.max_dx <= t)
        && (!g.rules || c.rule_diff.is_none())
}

/// The cases of a group: `(stem, docx bytes, Word lines)`.
fn cases(group: &str) -> Vec<(String, Vec<u8>, Doc)> {
    let dir = oracle_dir(group);
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .flatten()
        .filter_map(|e| e.file_name().to_str().and_then(|n| n.strip_suffix(".docx")).map(str::to_owned))
        .collect();
    names.sort();
    names
        .into_iter()
        .filter_map(|n| {
            let json = std::fs::read_to_string(dir.join(format!("{n}.word.json"))).ok()?;
            Some((n.clone(), std::fs::read(dir.join(format!("{n}.docx"))).unwrap(), word_lines(&json)))
        })
        .collect()
}

fn dump(name: &str, word: &Doc, ours: &Doc, tag: &str) {
    for pi in 0..word.pages.len().max(ours.pages.len()) {
        for l in word.pages.get(pi).into_iter().flatten() {
            println!("W p{} {:7.2} {:7.2}-{:7.2} {}", pi + 1, l.y, l.x0, l.x1, l.text);
        }
        for l in ours.pages.get(pi).into_iter().flatten() {
            println!("{tag} p{} {:7.2} {:7.2}-{:7.2} {}", pi + 1, l.y, l.x0, l.x1, l.text);
        }
        for (who, d) in [("W", word), (tag, ours)] {
            for r in d.rules.get(pi).into_iter().flatten() {
                println!(
                    "{who} p{} {} c {:.2} w {:.2} {:.2}..{:.2}",
                    pi + 1,
                    if r.vertical { "VLINE" } else { "HLINE" },
                    r.c,
                    r.t,
                    r.a,
                    r.b
                );
            }
        }
    }
    let _ = name;
}

fn run_group(g: &Group) {
    let verbose = std::env::var_os("UO_WC_VERBOSE").is_some();
    let all = cases(g.name);
    assert!(!all.is_empty(), "{}: no cases", g.name);
    let (mut bad, mut ts_bad) = (Vec::new(), Vec::new());
    let (mut lines, mut max_dy, mut max_dx) = (0usize, 0f64, 0f64);
    for (name, bytes, word) in &all {
        let ours = engine_lines(&lay(bytes, &opts()));
        let ts = engine_lines(&lay(bytes, &opts().ts_strict()));
        if std::env::var("UO_WC_DUMP").is_ok_and(|d| d.split(',').any(|d| d == *name)) {
            println!("## {name}");
            dump(name, word, &ours, "O");
            dump(name, word, &ts, "T");
        }
        let c = compare(word, &ours);
        let t = compare(word, &ts);
        lines += c.lines_w;
        max_dy = jm::max(max_dy, c.max_dy);
        max_dx = jm::max(max_dx, c.max_dx);
        if verbose {
            println!(
                "{name}: {} pages {}/{} lines {}/{} same page {} dy {:.2} dx {:.2} {:?} {:?} | ts {} pages {} matched {} same {} dx {:.2} {:?} {:?}",
                if equal(&c, g) { "EQ" } else { "DIFF" },
                c.pages_o,
                c.pages_w,
                c.matched,
                c.lines_w,
                c.same_page,
                c.max_dy,
                c.max_dx,
                c.first_diff,
                c.rule_diff,
                if equal(&t, g) { "EQ" } else { "DIFF" },
                t.pages_o,
                t.matched,
                t.same_page,
                t.max_dx,
                t.first_diff,
                t.rule_diff
            );
        }
        if g.open.contains(&name.as_str()) {
            assert!(!equal(&c, g), "{name} is listed open but equals Word now: drop it from the list");
        } else if !equal(&c, g) {
            bad.push(format!("{name}: {c:?}"));
        }
        if !equal(&t, g) {
            ts_bad.push(name.clone());
        }
    }
    println!(
        "{}: {} cases, {} lines, max Δy {:.2} pt, max Δx {:.2} pt; ts_strict differs from Word in {}",
        g.name,
        all.len(),
        lines,
        max_dy,
        max_dx,
        ts_bad.len()
    );
    assert!(bad.is_empty(), "{}: Word's rules differ from Word:\n{}", g.name, bad.join("\n"));
    let mut want: Vec<String> = g.ts_diverges.iter().map(|s| (*s).to_owned()).collect();
    want.sort();
    ts_bad.sort();
    assert_eq!(ts_bad, want, "{}: the cases where the frozen TS's rules differ from Word", g.name);
}

