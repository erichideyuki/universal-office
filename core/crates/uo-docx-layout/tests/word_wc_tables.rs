/// The six switches of the tables area: each turned to Word's rule alone over `ts_strict()` (attribution), and all of
/// them together (the area's agreement with Word).
type Flip = fn(&mut LayoutOptions);
const FLIPS: [(&str, Flip); 6] = [
    ("row_keep_any_paragraph", |o| o.ts_row_keep_any_paragraph = false),
    ("table_style_cell_borders", |o| o.ts_table_style_cell_borders = false),
    ("float_table_wrap_edge", |o| o.ts_float_table_wrap_edge = false),
    ("cell_float_no_clamp", |o| o.ts_cell_float_no_clamp = false),
    ("gap_word_any_mode", |o| o.ts_gap_word_any_mode = false),
    ("tbl_style_order", |o| o.ts_tbl_style_order = false),
];

/// `ts_strict()` with the tables area's switches at Word's rules (every other area's at the frozen TS's).
fn tables_word(o: LayoutOptions) -> LayoutOptions {
    let mut o = o.ts_strict();
    for (_, f) in &FLIPS {
        f(&mut o);
    }
    o
}

/// Opt-in (`UO_WC_ORACLE=<dir of oracle groups>`, the frozen TS root's `write/packages/docx-layout/test/oracle`, 2,742
/// documents; installed fonts, uo-fonts' oracle policy): "Word agreement may only go up" for THIS area. Every case is
/// laid out with `ts_strict()` and with the tables switches at Word's rules ([`tables_word`]); where the two differ,
/// both are compared with the case's `.word.json`. Fails when a changed case went from equal to different.
#[test]
fn tables_rules_agreement_on_the_oracle() {
    let Ok(root) = std::env::var("UO_WC_ORACLE") else {
        println!("skipped: set UO_WC_ORACLE to a directory of oracle groups");
        return;
    };
    use uo_docx_layout::options::{RevisionMode, RevisionView};
    let dy_tol = |g: &str| match g {
        "vertalign" => 0.6,
        "notes" | "fnsep" | "fnrefsup" => 0.65,
        "omath" => 0.4,
        _ => 0.3,
    };
    let source: std::sync::Arc<dyn uo_fonts::registry::FaceSource> = uo_fonts::system::SystemFontIndex::shared();
    let registry = std::sync::Arc::new(
        uo_fonts::registry::FontRegistry::new(
            uo_fonts::registry::FontBudget::of(uo_fonts::registry::FontProfile::Desktop),
            uo_fonts::registry::FaceCache::shared(),
        )
        .with_source(source),
    );
    let provider = uo_fonts::policy::provider(&registry, uo_fonts::policy::PolicyName::Oracle).unwrap();
    let mut groups: Vec<_> = std::fs::read_dir(&root).unwrap().flatten().map(|e| e.path()).filter(|p| p.is_dir()).collect();
    groups.sort();
    let (mut total, mut changed, mut before, mut after) = (0usize, 0usize, 0usize, 0usize);
    let mut worse = Vec::new();
    let pages = |l: &Layout| format!("{:?}", l.pages.iter().map(|p| &p.page).collect::<Vec<_>>());
    for gdir in groups {
        let g = gdir.file_name().unwrap().to_string_lossy().into_owned();
        let mut names: Vec<String> = std::fs::read_dir(&gdir)
            .unwrap()
            .flatten()
            .filter_map(|e| e.file_name().to_str().and_then(|n| n.strip_suffix(".docx")).map(str::to_owned))
            .collect();
        names.sort();
        let mut g_changed = Vec::new();
        for n in names {
            let Ok(json) = std::fs::read_to_string(gdir.join(format!("{n}.word.json"))) else { continue };
            total += 1;
            let bytes = std::fs::read(gdir.join(format!("{n}.docx"))).unwrap();
            let pkg = uo_opc::Package::open(&bytes, &Default::default(), &Default::default()).unwrap();
            let Ok(doc) = read_document(&pkg, &ReadOptions::default()) else { continue };
            let mut o = opts();
            if n.starts_with("mk-") {
                o.revisions = Some(RevisionView { mode: RevisionMode::All, ..RevisionView::default() });
            }
            let mut eng = LayoutEngine::with_hyphenation(common::hyph::hyph_registry());
            let Ok(ts) = eng.layout(DocView::new(&doc), &*provider, &o.clone().ts_strict()).cloned() else { continue };
            let mut eng = LayoutEngine::with_hyphenation(common::hyph::hyph_registry());
            let Ok(w) = eng.layout(DocView::new(&doc), &*provider, &tables_word(o)).cloned() else { continue };
            if pages(&ts) == pages(&w) {
                continue;
            }
            changed += 1;
            let word = word_lines(&json);
            let ok = |c: &Cmp| c.pages_o == c.pages_w && c.matched == c.lines_w && c.same_page == c.matched && c.max_dy <= dy_tol(&g);
            let (b, a) = (ok(&compare(&word, &engine_lines(&ts))), ok(&compare(&word, &engine_lines(&w))));
            before += usize::from(b);
            after += usize::from(a);
            if b && !a {
                worse.push(format!("{g}/{n}"));
            }
            g_changed.push(format!("{n} ({}→{})", if b { "equal" } else { "differs" }, if a { "equal" } else { "differs" }));
        }
        if !g_changed.is_empty() {
            println!("{g}: {}", g_changed.join(", "));
        }
    }
    println!(
        "oracle: {total} cases, {changed} change under the tables rules; Word-equal among them: TS rules {before}, Word rules {after}"
    );
    assert!(worse.is_empty(), "equal to Word with the TS rules, different with Word's: {worse:?}");
}

/// Opt-in (`UO_WC_ATTR=<dir of .docx>`; `UO_WC_ATTR_SOURCES=1` reads as the editor does): which tables switch changes
/// each document's pages (the harness declarations name the switch) — each turned to Word's rule alone over
/// `ts_strict()`, with the pages it changes (0-based).
#[test]
fn attribute_documents_to_the_tables_rules() {
    let Ok(dir) = std::env::var("UO_WC_ATTR") else {
        println!("skipped: set UO_WC_ATTR");
        return;
    };
    let mut files: Vec<_> =
        std::fs::read_dir(&dir).unwrap().flatten().map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "docx")).collect();
    files.sort();
    let sources = std::env::var_os("UO_WC_ATTR_SOURCES").is_some();
    let lay_opt = |b: &[u8], o: &LayoutOptions| -> Option<Layout> {
        let pkg = uo_opc::Package::open(b, &Default::default(), &Default::default()).ok()?;
        let doc = read_document(&pkg, &ReadOptions { sources, ..ReadOptions::default() }).ok()?;
        let fonts = OpenFonts::at(&common::repo());
        let mut eng = LayoutEngine::with_hyphenation(common::hyph::hyph_registry());
        eng.layout(DocView::new(&doc), &fonts, o).ok().cloned()
    };
    let per_page = |l: &Layout| l.pages.iter().map(|p| format!("{:?}", p.page)).collect::<Vec<_>>();
    for p in files {
        let bytes = std::fs::read(&p).unwrap();
        let Some(base_l) = lay_opt(&bytes, &opts().ts_strict()) else { continue };
        let base_p = per_page(&base_l);
        let mut hit = Vec::new();
        for (n, f) in &FLIPS {
            let mut o = opts().ts_strict();
            f(&mut o);
            let Some(l) = lay_opt(&bytes, &o) else { continue };
            let pp = per_page(&l);
            if pp != base_p {
                let changed: Vec<String> =
                    (0..pp.len().max(base_p.len())).filter(|&i| pp.get(i) != base_p.get(i)).map(|i| i.to_string()).collect();
                hit.push(format!("{n} [pages {} → {}; changed {}]", base_p.len(), pp.len(), changed.join(" ")));
            }
        }
        println!("{}: {}", p.file_name().unwrap().to_string_lossy(), if hit.is_empty() { "-".to_owned() } else { hit.join(", ") });
    }
}

/// Opt-in (`UO_WC_FACETS=<dir of .docx>`): the viewer harness facets (`uo-wasm/tests/browser/viewer_switch.mjs`
/// `compare`) each tables switch should change in a document, predicted natively from `ts_strict()` against
/// `ts_strict()` with that switch at Word's rule (the open fonts): `pages` (the count), `pixels` (the pages whose painted
/// content differs), `textLayer` (the pages whose lines — text, baseline, x — differ), `find` (the harness's queries: the
/// five most frequent words of 4+ letters of the TS text, plus the first accented one, counted per page), `linkBoxes`
/// (a line with a hyperlink's text — "link N" in the capture fixtures — moves) and `pdf`. A prediction for the harness
/// declarations (`WC_TABLES`), which the harness run itself confirms.
#[test]
fn predict_viewer_facets_of_the_tables_rules() {
    let Ok(dir) = std::env::var("UO_WC_FACETS") else {
        println!("skipped: set UO_WC_FACETS");
        return;
    };
    let mut files: Vec<_> =
        std::fs::read_dir(&dir).unwrap().flatten().map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "docx")).collect();
    files.sort();
    let page_texts =
        |d: &Doc| -> Vec<String> { d.pages.iter().map(|p| p.iter().map(|l| l.text.to_lowercase()).collect::<Vec<_>>().join("")).collect() };
    let words = |t: &str| -> Vec<String> {
        let mut out = Vec::new();
        let mut cur = String::new();
        for c in t.chars().chain(std::iter::once(' ')) {
            if c.is_alphabetic() {
                cur.push(c);
            } else {
                if cur.chars().count() >= 4 {
                    out.push(cur.clone());
                }
                cur.clear();
            }
        }
        out
    };
    for p in files {
        let bytes = std::fs::read(&p).unwrap();
        let base = lay(&bytes, &opts().ts_strict());
        let bp: Vec<String> = base.pages.iter().map(|pg| format!("{:?}", pg.page)).collect();
        for (n, f) in &FLIPS {
            let mut o = opts().ts_strict();
            f(&mut o);
            let l = lay(&bytes, &o);
            let sp: Vec<String> = l.pages.iter().map(|pg| format!("{:?}", pg.page)).collect();
            if sp == bp {
                continue;
            }
            let n0 = bp.len().min(sp.len());
            let (bd, sd) = (engine_lines(&base), engine_lines(&l));
            let mut facets = Vec::new();
            if bp.len() != sp.len() {
                facets.push("pages".to_owned());
            }
            let key = |l: &Line| format!("{:.2} {:.2} {}", l.y, l.x0, l.text);
            let text_pages: Vec<usize> = (0..n0)
                .filter(|&i| bd.pages[i].iter().map(key).collect::<Vec<_>>() != sd.pages[i].iter().map(key).collect::<Vec<_>>())
                .collect();
            let link = |d: &Doc| -> Vec<String> {
                d.pages
                    .iter()
                    .enumerate()
                    .flat_map(|(i, pg)| pg.iter().filter(|l| l.text.contains("link")).map(move |l| format!("{i} {}", key(l))))
                    .collect()
            };
            if link(&bd) != link(&sd) {
                facets.push("linkBoxes".to_owned());
            }
            if !text_pages.is_empty() {
                facets.push("textLayer".to_owned());
            }
            let (bt, st) = (page_texts(&bd), page_texts(&sd));
            let mut freq: std::collections::BTreeMap<String, usize> = std::collections::BTreeMap::new();
            for t in &bt {
                for w in words(t) {
                    *freq.entry(w).or_insert(0) += 1;
                }
            }
            let mut by: Vec<(&String, &usize)> = freq.iter().collect();
            by.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
            let mut queries: Vec<String> = by.iter().take(5).map(|e| e.0.clone()).collect();
            if let Some(a) = freq.keys().find(|w| !w.is_ascii()) {
                queries.push(a.clone());
            }
            let find = queries.iter().any(|q| (0..n0).any(|i| bt[i].matches(q.as_str()).count() != st[i].matches(q.as_str()).count()));
            if find {
                facets.push("find".to_owned());
            }
            let px: Vec<usize> = (0..n0).filter(|&i| bp[i] != sp[i]).collect();
            if !px.is_empty() {
                facets.push("pixels".to_owned());
            }
            facets.push("pdf".to_owned());
            println!(
                "{} {n}: pages {} → {}; facets {}; textLayer pages {:?}; pixels pages {:?}",
                p.file_stem().unwrap().to_string_lossy(),
                bp.len(),
                sp.len(),
                facets.join(","),
                text_pages,
                px
            );
        }
    }
}

