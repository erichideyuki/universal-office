//! WordCraft study — tables (record `core/docs/modules/uo-docx-layout.md` "WordCraft study — tables"): the Rust layout
//! against Microsoft Word's own PDFs for the table rules the study measured.
//!
//! The comparer is the one of `word_w7c.rs` (a port of the frozen TS `test/oracle-compare.ts`: pages, line texts in
//! order, the page of each line, baseline ±0.3 pt, x where the group measures it), plus a RULES comparer for the
//! border groups: Word's vertical and horizontal paths (`objs` of the `.word.json`, the classification of the study's
//! `wsum.py`: w < 4 and h > 4 pt vertical, h < 4 and w > 4 pt horizontal) against the layout's border lines of the
//! same page — collinear pieces joined, then centre ±0.3 pt, thickness ±0.15 pt, ends ±0.6 pt (plus half the thickest
//! crossing border: Word joins the corners).
//!
//! The groups live in `tests/oracle_wc/<group>` (open fonts only: Liberation Sans), generated by
//! `write/tools/layout-oracle/cases/wctab*.mjs` and the B study's `wcb*.mjs` (`run.mjs <group> --fixdir`); the
//! `w2-` prefix marks the second-round cases of `wctab2` whose names clash with `wctabft`'s.
//!
//! Each case is laid out with the default options (Word's rules: must equal Word) and with `LayoutOptions::ts_strict()`
//! (the frozen TS's rules): the cases where the TS differs are listed per group (`ts_diverges`).
//!
//!   cargo test -j 3 --release -p uo-docx-layout --test word_wc_tables -- --test-threads=3
//!   UO_WC_VERBOSE=1: one line per case; UO_WC_DUMP=<case>: Word's and our lines and rules of the case

