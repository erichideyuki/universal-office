#[cfg(test)]
mod tests {
    use super::symbol_unicode;

    #[test]
    fn the_encoding() {
        assert_eq!(symbol_unicode(0x61), Some(0x3b1));
        assert_eq!(symbol_unicode(0xf0b7), Some(0x2022));
        assert_eq!(symbol_unicode(0x41), Some(0x391));
        assert_eq!(symbol_unicode(0xf0e5), Some(0x2211));
        assert_eq!(symbol_unicode(0x80), None);
        assert_eq!(symbol_unicode(0x7f), None);
    }
}
