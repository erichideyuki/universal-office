// Generates src/catalog_tables.rs from the frozen TS catalog (shared/fonts/src/catalog.ts, G9):
// the bundled families, the metric substitutes and the probe families, in the TS order (object
// keys and array elements as written, duplicates kept). Run once; the output is checked in.
//
//   node tools/gen_catalog.mjs --ts-root <built checkout of main>     (or UO_TS_ROOT)
//
// The checkout is never a path written in the repository. The output is deterministic: running
// it twice over the same TS gives the same bytes. The re-parse test in src/catalog.rs reads the
// TS source while it exists and fails if the tables drift.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { importFrom, tsRoot } from '../../uo-testkit/js/testkit.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const catalog = await importFrom(tsRoot(), 'shared/fonts/dist/catalog.js');

// own keys that look like an integer would be reordered by V8 and break the "TS order" promise
for (const table of [catalog.BUNDLED, catalog.METRIC_SUBSTITUTES]) {
  for (const k of Object.keys(table)) if (/^(0|[1-9]\d*)$/.test(k)) throw new Error(`integer-like key ${k}`);
}

const lit = (s) => {
  if (/[\\"\u0000-\u001f\u007f-￿]/.test(s)) throw new Error(`unexpected character in ${JSON.stringify(s)}`);
  return `"${s}"`;
};

const lines = [
  '// Generated by tools/gen_catalog.mjs from shared/fonts/src/catalog.ts (G9) - do not edit.',
  '',
  `pub const DEFAULT_FAMILY: &str = ${lit(catalog.DEFAULT_FAMILY)};`,
  '',
  '/// Lower-case family key to the bundled open family, in the TS order.',
  'pub const BUNDLED: &[(&str, BundledFamily)] = &[',
  ...Object.entries(catalog.BUNDLED).map(([k, v]) => `    (${lit(k)}, BundledFamily { family: ${lit(v.family)}, file: ${lit(v.file)} }),`),
  '];',
  '',
  '/// Lower-case family key to substitute, in the TS order.',
  'pub const METRIC_SUBSTITUTES: &[(&str, &str)] = &[',
  ...Object.entries(catalog.METRIC_SUBSTITUTES).map(([k, v]) => `    (${lit(k)}, ${lit(v)}),`),
  '];',
  '',
  '/// Families worth probing when the browser does not enumerate the installed fonts (TS order,',
  '/// duplicates kept).',
  'pub const PROBE_FAMILIES: &[&str] = &[',
  ...catalog.PROBE_FAMILIES.map((f) => `    ${lit(f)},`),
  '];',
  '',
];
const out = join(here, '..', 'src', 'catalog_tables.rs');
writeFileSync(out, lines.join('\n'));
console.log(`${out}: ${Object.keys(catalog.BUNDLED).length} bundled, ${Object.keys(catalog.METRIC_SUBSTITUTES).length} substitutes, ${catalog.PROBE_FAMILIES.length} probes`);
