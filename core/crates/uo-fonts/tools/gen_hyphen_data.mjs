// Generates data/hyphen/<id>.txt from the frozen TS pattern modules (G7): the Liang patterns and
// exceptions of the seven languages, one text file each, plus the third-party notices. Run once;
// the output is checked in. The files are data, not code: the wasm build never contains them,
// the native and .NET builds embed them with the feature `hyphen-data`.
//
//   node tools/gen_hyphen_data.mjs --ts-root <built checkout of main>     (or UO_TS_ROOT)
//
// Deterministic: the same TS gives the same bytes. The checkout is never a path in the repo.
//
// What the TS did at run time and the Rust port does not: it normalized every pattern and every
// exception to NFC when it built the hyphenator. The shipped data must therefore already be NFC
// (the Rust side compares code points as they are), and this generator fails otherwise. The
// exception key is `word.replace(/-/g, '').normalize('NFC').toLowerCase()` there but the break
// positions come from the NFC form with the dashes in place, so a word is also required to be
// the same NFC with the dashes removed.
//
// File format (UTF-8, LF): `#` lines are the notice of the source (copyright and licence);
// then `id <id>`, `left <n>`, `right <n>`, a `[patterns]` line and the patterns separated by
// spaces (wrapped at 120 columns), an `[exceptions]` line and the exceptions likewise.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { importFrom, tsRoot } from '../../uo-testkit/js/testkit.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = tsRoot();
const base = 'write/packages/docx-layout';
const outDir = join(here, '..', 'data', 'hyphen');
mkdirSync(outDir, { recursive: true });

const IDS = ['pt', 'en-us', 'es', 'fr', 'de-1996', 'it', 'nl'];
const JS_SPACE = /\s+/; // the TS split on /\s+/

function wrap(tokens, width = 120) {
  const lines = [];
  let line = '';
  for (const t of tokens) {
    if (line && line.length + 1 + t.length > width) { lines.push(line); line = t; }
    else line = line ? `${line} ${t}` : t;
  }
  if (line) lines.push(line);
  return lines;
}

function banner(id) {
  const src = readFileSync(join(root, base, 'src/typography/hyphen/patterns', `${id}.ts`), 'utf8').replace(/\r\n/g, '\n');
  const m = /^\/\*!\s*@license\n([\s\S]*?)\n\s*\*\//.exec(src);
  if (!m) throw new Error(`${id}: no license banner`);
  return m[1].split('\n').map((l) => `# ${l.replace(/^ \* ?/, '')}`.trimEnd());
}

const report = [];
for (const id of IDS) {
  const { default: data } = await importFrom(root, `${base}/dist/typography/hyphen/patterns/${id}.js`);
  if (data.id !== id) throw new Error(`${id}: id ${data.id}`);
  const patterns = data.patterns.split(JS_SPACE).filter(Boolean);
  const exceptions = data.exceptions.split(JS_SPACE).filter(Boolean);
  for (const p of patterns) if (p.normalize('NFC') !== p) throw new Error(`${id}: pattern ${JSON.stringify(p)} is not NFC`);
  for (const e of exceptions) {
    if (e.normalize('NFC') !== e) throw new Error(`${id}: exception ${JSON.stringify(e)} is not NFC`);
    const bare = e.replace(/-/g, '');
    if (bare.normalize('NFC') !== bare) throw new Error(`${id}: exception ${JSON.stringify(e)} is not NFC without its dashes`);
  }
  const lines = [
    ...banner(id),
    '',
    '# Generated by tools/gen_hyphen_data.mjs from the frozen TS patterns (G7) - do not edit.',
    `id ${id}`,
    `left ${data.left}`,
    `right ${data.right}`,
    '[patterns]',
    ...wrap(patterns),
    '[exceptions]',
    ...wrap(exceptions),
  ];
  writeFileSync(join(outDir, `${id}.txt`), `${lines.join('\n')}\n`);
  report.push(`${id}: ${patterns.length} patterns, ${exceptions.length} exceptions, minimums ${data.left}/${data.right}`);
}
const notices = readFileSync(join(root, base, 'src/typography/hyphen/patterns/THIRD-PARTY-NOTICES.md'), 'utf8').replace(/\r\n/g, '\n');
writeFileSync(join(outDir, 'THIRD-PARTY-NOTICES.md'), notices);
console.log(report.join('\n'));
