// Generates src/tables/*.rs from the frozen TS sources of shared/drawingml (G11): the preset
// definitions (preset-defs.ts, tokenized exactly like parseDef of preset-engine.ts), the light
// tables and bevel profiles (light3d.ts), the Word bevel tables (bevel-word.ts), the preset
// patterns (patterns.ts), the image adjustment curves (adjust.ts) and the sRGB lookup tables
// (bevel.ts SRGB_LIN / LIN_SRGB). Run once; the output is checked in.
//
//   node tools/gen-tables.mjs --ts-root <checkout of main>     (or UO_TS_ROOT)
//
// Options:
//   --out <dir>   write the tables there instead of src/tables (the re-run test)
//   --no-srgb     skip srgb.rs (it needs the pow reference platform, see below)
//
// The checkout is never a path written in the repository. The output is deterministic: a re-run
// over the same TS gives the same bytes. srgb.rs evaluates `Math.pow`, whose bits depend on the
// platform (uo-jsnum gate, G2 option (a)): the script refuses to write it anywhere but Node
// 24.15.0 linux-x64 with the FMA variant of glibc's pow masked, i.e. in WSL:
//
//   GLIBC_TUNABLES=glibc.cpu.hwcaps=-FMA,-AVX2 node tools/gen-tables.mjs --ts-root <checkout>
//
// The re-parse test (tests/tables.rs) reads the TS sources while they exist and compares every
// table; for srgb.rs it recomputes the tables with uo_jsnum::math::pow.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { tsRoot } from '../../uo-testkit/js/testkit.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const opt = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
const outDir = opt('--out') ?? join(here, '..', 'src', 'tables');
const root = tsRoot(argv);
const src = (name) => readFileSync(join(root, 'shared', 'drawingml', 'src', name), 'utf8');

// ── reading the TS ──────────────────────────────────────────────────────────────────────────────

/** The literal (`{...}` or `[...]`) a top-level `const NAME ... = <literal>` of a TS source holds, evaluated. */
function literal(text, name) {
  const m = new RegExp(`(?:^|\\n)(?:export\\s+)?const\\s+${name}\\b`).exec(text);
  if (!m) throw new Error(`const ${name} not found`);
  let i = text.indexOf('=', m.index + m[0].length);
  while (/\s/.test(text[i + 1])) i++;
  i++;
  const open = text[i];
  if (open !== '{' && open !== '[') throw new Error(`${name}: no literal after =`);
  const start = i;
  let depth = 0;
  for (; i < text.length; i++) {
    const c = text[i];
    if (c === "'" || c === '"' || c === '`') {
      for (i++; text[i] !== c; i++) if (text[i] === '\\') i++;
    } else if (c === '/' && text[i + 1] === '/') {
      while (text[i] !== '\n') i++;
    } else if (c === '/' && text[i + 1] === '*') {
      i = text.indexOf('*/', i) + 1;
    } else if (c === '{' || c === '[') depth++;
    else if (c === '}' || c === ']') { depth--; if (depth === 0) break; }
  }
  return vm.runInNewContext(`(${text.slice(start, i + 1)})`, Object.create(null));
}

// own keys that look like an integer would be reordered by V8 and break the "file order" promise
function ownKeys(obj, what) {
  const keys = Object.keys(obj);
  for (const k of keys) if (/^(0|[1-9]\d*)$/.test(k)) throw new Error(`${what}: integer-like key ${k}`);
  return keys;
}

// ── formatting the Rust ─────────────────────────────────────────────────────────────────────────

const lit = (s) => {
  if (!/^[\x20-\x7e]*$/.test(s) || /["\\]/.test(s)) throw new Error(`unexpected character in ${JSON.stringify(s)}`);
  return `"${s}"`;
};
const f64 = (n) => {
  if (!Number.isFinite(n) || Object.is(n, -0)) throw new Error(`bad number ${n}`);
  const s = String(n);
  if (/e/i.test(s)) throw new Error(`exponent form ${s}`);
  return /^-?\d+$/.test(s) ? `${s}.0` : s;
};
const optF64 = (n) => (n === undefined ? 'None' : `Some(${f64(n)})`);
const header = (what) => [`// Generated by tools/gen-tables.mjs from ${what} (G11) - do not edit.`, ''];
const byteRows = (bytes, per = 24) => {
  const rows = [];
  for (let i = 0; i < bytes.length; i += per) rows.push(`        ${Array.from(bytes.subarray(i, i + per)).join(', ')},`);
  return rows;
};
const write = (name, lines) => {
  mkdirSync(outDir, { recursive: true });
  const text = lines.join('\n');
  if (text.includes('\r')) throw new Error('CR in output');
  writeFileSync(join(outDir, name), text);
  console.log(`${join(outDir, name)}: ${text.length} bytes`);
};

// ── presets (preset-defs.ts + parseDef of preset-engine.ts) ─────────────────────────────────────

const OPS = {
  val: 'Val', '*/': 'MulDiv', '+-': 'AddSub', '+/': 'AddDiv', '?:': 'IfElse', abs: 'Abs', at2: 'At2', cat2: 'Cat2', sat2: 'Sat2',
  cos: 'Cos', sin: 'Sin', tan: 'Tan', max: 'Max', min: 'Min', mod: 'Mod', pin: 'Pin', sqrt: 'Sqrt',
};
const SHADE = { none: null, darken: -0.4, darkenLess: -0.2, lighten: 0.4, lightenLess: 0.2 };

// parseDef of preset-engine.ts, tokenized the same way (it is not exported)
function parseDef(raw) {
  const [av = '', gd = '', ps = '', rc = ''] = raw.split('|');
  const words = (s) => s.trim().split(/\s+/).filter(Boolean);
  const guides = (s) => (s ? s.split(';').map((e) => {
    const i = e.indexOf('=');
    if (i < 0) throw new Error(`guide without '=': ${e}`);
    return [e.slice(0, i).trim(), words(e.slice(i + 1))];
  }) : []);
  const paths = ps ? ps.split('#').map((p) => {
    const [attrs = '', cmds = ''] = p.split('~');
    const [w = '', h = '', fill = '', stroke = ''] = attrs.split(',');
    const d = { fill, stroke: stroke !== 'false' && stroke !== '0', cmds: cmds ? cmds.split(';').map(words) : [] };
    if (w) d.w = Number(w);
    if (h) d.h = Number(h);
    return d;
  }) : [];
  const def = { av: guides(av), gd: guides(gd), paths };
  const rw = words(rc);
  if (rw.length === 4) def.rect = rw;
  return def;
}

function genPresets() {
  const defs = literal(src('preset-defs.ts'), 'PRESET_DEFS');
  const names = ownKeys(defs, 'PRESET_DEFS');
  for (const n of names) if (!/^[A-Za-z0-9]+$/.test(n)) throw new Error(`preset name ${n}`);
  const token = (t) => {
    if (!/^[\x21-\x7e]+$/.test(t) || /["\\]/.test(t)) throw new Error(`token ${JSON.stringify(t)}`);
    return `"${t}"`;
  };
  const guide = ([name, f]) => {
    const op = f[0];
    if (!Object.prototype.hasOwnProperty.call(OPS, op)) throw new Error(`unknown guide op ${op} in ${name}`);
    const a = [f[1] ?? '0', f[2] ?? '0', f[3] ?? '0'];
    return `g(${lit(name)}, Op::${OPS[op]}, ${a.map(token).join(', ')})`;
  };
  const cmd = (c) => {
    const op = c[0] !== undefined && /^[MLQCAZ]$/.test(c[0]) ? `b'${c[0]}'` : '0';
    return `c(${op}, &[${c.slice(1).map(token).join(', ')}])`;
  };
  const path = (p) => {
    if (p.fill !== '' && !Object.prototype.hasOwnProperty.call(SHADE, p.fill)) throw new Error(`fill ${p.fill}`);
    const fill = p.fill === '' ? 0 : SHADE[p.fill];
    return `p(${optF64(p.w)}, ${optF64(p.h)}, ${fill === null ? 'None' : `Some(${f64(fill)})`}, ${p.stroke}, &[${p.cmds.map(cmd).join(', ')}])`;
  };
  const lines = [...header('shared/drawingml/src/preset-defs.ts'), '/// Every preset of the official definitions in the TS key order: guides, paths and text rectangle.', 'pub(crate) static PRESETS: &[(&str, PresetDef)] = &['];
  for (const name of names) {
    const d = parseDef(defs[name]);
    const rect = d.rect ? `Some([${d.rect.map(token).join(', ')}])` : 'None';
    lines.push(`    (${lit(name)}, PresetDef {`);
    lines.push(`        av: &[${d.av.map(guide).join(', ')}],`);
    lines.push(`        gd: &[${d.gd.map(guide).join(', ')}],`);
    lines.push(`        paths: &[${d.paths.map(path).join(', ')}],`);
    lines.push(`        rect: ${rect},`);
    lines.push('    }),');
  }
  lines.push('];', '');
  const sorted = names.map((n, i) => [n, i]).sort((x, y) => (x[0] < y[0] ? -1 : x[0] > y[0] ? 1 : 0));
  lines.push('/// Indices into `PRESETS` ordered by name (byte order), for the binary search of the lookup.');
  lines.push('pub(crate) static PRESET_INDEX: &[u16] = &[');
  for (let i = 0; i < sorted.length; i += 20) lines.push(`    ${sorted.slice(i, i + 20).map((s) => s[1]).join(', ')},`);
  lines.push('];', '');
  write('presets.rs', lines);
  return names.length;
}

// ── light3d.ts and bevel-word.ts ────────────────────────────────────────────────────────────────

const decode = (b64) => Uint8Array.from(Buffer.from(b64, 'base64'));

function genLight() {
  const text = src('light3d.ts');
  const tables = literal(text, 'TABLES');
  const profiles = literal(text, 'PROFILES');
  const lines = [...header('shared/drawingml/src/light3d.ts'), '/// Light tables by `rig|material` in the TS key order: 24 azimuths x 11 polar angles x (Dr, Dg, Db, S), then the face sample.', 'pub(crate) static LIGHT_TABLES: &[(&str, &[u8])] = &['];
  for (const k of ownKeys(tables, 'TABLES')) {
    const bytes = decode(tables[k]);
    if (bytes.length !== (24 * 11 + 1) * 4) throw new Error(`light table ${k}: ${bytes.length} bytes`);
    lines.push(`    (${lit(k)}, &[`, ...byteRows(bytes), '    ]),');
  }
  lines.push('];', '', '/// Measured polar angles (degrees) of the bevel normal at the 24 distances, by preset, in the TS key order.', 'pub(crate) static PROFILES: &[(&str, &[f64])] = &[');
  for (const k of ownKeys(profiles, 'PROFILES')) {
    if (profiles[k].length !== 24) throw new Error(`profile ${k}`);
    lines.push(`    (${lit(k)}, &[${profiles[k].map(f64).join(', ')}]),`);
  }
  lines.push('];', '');
  write('light.rs', lines);
  return [Object.keys(tables).length, Object.keys(profiles).length];
}

function genWordBevel() {
  const tables = literal(src('bevel-word.ts'), 'WORD_BEVEL');
  const lines = [...header('shared/drawingml/src/bevel-word.ts'), '/// Word bevel light by preset in the TS key order: 24 azimuths x 25 distances x (D, S).', 'pub(crate) static WORD_BEVEL: &[(&str, &[u8])] = &['];
  for (const k of ownKeys(tables, 'WORD_BEVEL')) {
    const bytes = decode(tables[k]);
    if (bytes.length !== 24 * 25 * 2) throw new Error(`word bevel ${k}: ${bytes.length} bytes`);
    lines.push(`    (${lit(k)}, &[`, ...byteRows(bytes), '    ]),');
  }
  lines.push('];', '');
  write('word_bevel.rs', lines);
  return Object.keys(tables).length;
}

// ── patterns.ts ─────────────────────────────────────────────────────────────────────────────────

function genPatterns() {
  const pats = literal(src('patterns.ts'), 'PRESET_PATTERNS');
  const lines = [...header('shared/drawingml/src/patterns.ts'), '/// The 8x8 preset patterns in the TS key order (bit 7 of a row = column 0).', 'pub(crate) static PRESET_PATTERNS: &[(&str, [u8; 8])] = &['];
  for (const k of ownKeys(pats, 'PRESET_PATTERNS')) {
    const hex = pats[k];
    if (!/^[0-9a-f]{16}$/.test(hex)) throw new Error(`pattern ${k}: ${hex}`);
    const rows = Array.from({ length: 8 }, (_, i) => parseInt(hex.slice(i * 2, i * 2 + 2), 16));
    lines.push(`    (${lit(k)}, [${rows.map((r) => `0x${r.toString(16).padStart(2, '0')}`).join(', ')}]),`);
  }
  lines.push('];', '');
  write('patterns.rs', lines);
  return Object.keys(pats).length;
}

// ── adjust.ts ───────────────────────────────────────────────────────────────────────────────────

function genAdjust() {
  const text = src('adjust.ts');
  const lut = (name) => literal(text, name).map(([p, s]) => {
    const k = s.split(' ').map(Number);
    if (k.length !== 33 || !k.every((v) => Number.isInteger(v) && v >= 0 && v <= 255)) throw new Error(`${name}: bad knots at ${p}`);
    return `    (${f64(p)}, [${k.join(', ')}]),`;
  });
  const temp = literal(text, 'TEMP_TABLE');
  const lines = [
    ...header('shared/drawingml/src/adjust.ts'),
    '/// Brightness curves measured in Word: (value, 33 knots every 8 levels plus 255), in the TS order.',
    'pub(crate) static BRIGHT_LUT: &[(f64, [u8; 33])] = &[', ...lut('BRIGHT_LUT'), '];', '',
    '/// Contrast curves measured in Word, as `BRIGHT_LUT`.',
    'pub(crate) static CONTRAST_LUT: &[(f64, [u8; 33])] = &[', ...lut('CONTRAST_LUT'), '];', '',
    '/// Maximum R and B shift per colour temperature: (kelvin, R, B).',
    'pub(crate) static TEMP_TABLE: &[(f64, f64, f64)] = &[',
    ...temp.map(([k, r, b]) => `    (${f64(k)}, ${f64(r)}, ${f64(b)}),`), '];', '',
  ];
  write('adjust.rs', lines);
}

// ── bevel.ts: SRGB_LIN and LIN_SRGB (Math.pow) ──────────────────────────────────────────────────

function genSrgb() {
  const tun = process.env.GLIBC_TUNABLES ?? '';
  if (process.version !== 'v24.15.0' || process.platform !== 'linux' || process.arch !== 'x64' || !tun.includes('glibc.cpu.hwcaps=-FMA,-AVX2') || process.execArgv.length) {
    throw new Error('srgb.rs evaluates Math.pow: run on Node v24.15.0 linux-x64 with GLIBC_TUNABLES=glibc.cpu.hwcaps=-FMA,-AVX2 and no Node flags (WSL), or pass --no-srgb');
  }
  // the loops of bevel.ts, verbatim
  const SRGB_LIN = new Float32Array(256);
  for (let v = 0; v < 256; v++) { const x = v / 255; SRGB_LIN[v] = x <= 0.04045 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4); }
  const LIN_SRGB = new Uint8Array(4096);
  for (let i = 0; i < 4096; i++) { const x = i / 4095; LIN_SRGB[i] = Math.round(255 * (x <= 0.0031308 ? x * 12.92 : 1.055 * Math.pow(x, 1 / 2.4) - 0.055)); }
  const bits = new Uint32Array(SRGB_LIN.buffer);
  const lines = [
    ...header('shared/drawingml/src/bevel.ts'),
    '// Evaluated by Node v24.15.0 linux-x64, glibc 2.39, GLIBC_TUNABLES=glibc.cpu.hwcaps=-FMA,-AVX2 (the pow reference of the uo-jsnum gate).',
    '',
    '/// `SRGB_LIN`: the f32 values (as bits) of the sRGB to linear curve at 0..=255.',
    'pub(crate) static SRGB_LIN_BITS: [u32; 256] = [',
  ];
  for (let i = 0; i < 256; i += 8) lines.push(`    ${Array.from(bits.subarray(i, i + 8)).map((b) => `0x${b.toString(16).padStart(8, '0')}`).join(', ')},`);
  lines.push('];', '', '/// `LIN_SRGB`: linear (x 4095) to sRGB, rounded to a byte.', 'pub(crate) static LIN_SRGB: [u8; 4096] = [', ...byteRows(LIN_SRGB, 32), '];', '');
  write('srgb.rs', lines);
}

const n = genPresets();
const [lt, lp] = genLight();
const wb = genWordBevel();
const pc = genPatterns();
genAdjust();
if (!argv.includes('--no-srgb')) genSrgb();
console.log(`${n} presets, ${lt} light tables, ${lp} profiles, ${wb} word bevels, ${pc} patterns`);
