// Generates `src/grid/data.rs`: the measured Excel tables of the frozen TS (glyph widths, row heights, digit widths,
// descents) as `&'static` data. Numbers only (measurements), no font files.
//
//   node core/crates/uo-xlsx/js/gen-grid-data.mjs [--ts-root <dir>] [--check]
//
// `--check` fails when the committed file differs from what the frozen TS gives.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { args, crateDir, tsRoot } from './lib/common.mjs';

const a = args();
const root = tsRoot(a);
const sp = join(root, 'sheet', 'packages');

/** Evaluates a data module of the frozen TS (plain `export const X: Type = …;`). */
async function load(rel) {
  const src = readFileSync(join(sp, rel), 'utf8').replace(/export const (\w+): [^=]+=/g, 'export const $1 =');
  return import(`data:text/javascript;base64,${Buffer.from(src).toString('base64')}`);
}

const rs = (s) => {
  let o = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') o += `\\${ch}`;
    else if (c >= 0x20 && c < 0x7f) o += ch;
    else o += `\\u{${c.toString(16)}}`;
  }
  return `${o}"`;
};
const noSurrogates = (s, what) => {
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdfff) throw new Error(`surrogate unit in ${what}`);
  }
};

const metrics = await load('sheet-core/src/excel-metrics-data.ts');
const glyphs = await load('sheet-core/src/glyph-widths-data.ts');
const descents = await load('sheet/src/row-descent-data.ts');

let out = '// GENERATED by core/crates/uo-xlsx/js/gen-grid-data.mjs from the frozen TS tables — do not edit by hand.\n';
out += '// Measured in Excel 365 / GDI (96 dpi): numbers only. Tables are sorted by key (binary search); a string holds one\n';
out += '// base-62 character per ppem (row heights, digit widths, descents) as in the TS, and `GLYPH_FIX` rows hold pairs\n';
out += '// (character, base-62 width) of the glyphs whose GDI advance differs from the rounded canvas advance.\n\n';
out += `pub const ROW_PPEM_MIN: i32 = ${metrics.ROW_PPEM_MIN};\npub const ROW_PPEM_MAX: i32 = ${metrics.ROW_PPEM_MAX};\n`;
out += `pub const MDW_PPEM_MIN: i32 = ${metrics.MDW_PPEM_MIN};\npub const MDW_PPEM_MAX: i32 = ${metrics.MDW_PPEM_MAX};\n`;
out += `pub const DESC_PPEM_MIN: i32 = ${descents.DESC_PPEM_MIN};\npub const DESC_PPEM_MAX: i32 = ${descents.DESC_PPEM_MAX};\n`;
out += `pub const GLYPH_PPEM_MIN: i32 = ${glyphs.GLYPH_PPEM_MIN};\npub const GLYPH_PPEM_MAX: i32 = ${glyphs.GLYPH_PPEM_MAX};\n\n`;

const table = (name, rec, doc) => {
  const keys = Object.keys(rec).sort();
  let s = `/// ${doc}\npub static ${name}: &[(&str, &str)] = &[\n`;
  for (const k of keys) { noSurrogates(k, name); s += `    (${rs(k)}, ${rs(rec[k])}),\n`; }
  return `${s}];\n\n`;
};
out += table('ROW_PX', metrics.ROW_PX, '`ROW_PX`: auto-fit row height (px) per family, ppem 4..96.');
out += table('ROW_PX_BOLD', metrics.ROW_PX_BOLD, '`ROW_PX_BOLD`: the same in bold, ppem 4..40.');
out += table('MDW', metrics.MDW, '`MDW`: maximum digit width of the Normal font, ppem 8..32.');
out += table('ROW_DESC', descents.ROW_DESC, '`ROW_DESC`: GDI `tmDescent`, ppem 4..40.');
out += table('ROW_DESC_BOLD', descents.ROW_DESC_BOLD, '`ROW_DESC_BOLD`: where bold differs.');

const gkeys = Object.keys(glyphs.GLYPH_FIX).sort();
out += '/// `GLYPH_FIX["family|bold"][ppem - 8]`: pairs (character, base-62 width).\npub static GLYPH_FIX: &[(&str, &[&str])] = &[\n';
for (const k of gkeys) {
  out += `    (${rs(k)}, &[\n`;
  for (const row of glyphs.GLYPH_FIX[k]) { noSurrogates(row, `GLYPH_FIX ${k}`); out += `        ${rs(row)},\n`; }
  out += '    ]),\n';
}
out += '];\n';

const target = join(crateDir, 'src', 'grid', 'data.rs');
if (a.flag('--check')) {
  const cur = readFileSync(target, 'utf8');
  if (cur !== out) { console.error('src/grid/data.rs differs from the frozen TS tables'); process.exit(1); }
  console.log('grid data: up to date');
} else {
  writeFileSync(target, out);
  console.log(`grid data: ${out.length} bytes -> ${target}`);
}
