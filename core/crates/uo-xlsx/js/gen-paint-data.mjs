// Generates `src/grid/table_style/data.rs`: the built-in table and pivot style definitions the frozen TS measured in
// Excel (`table-styles-data.ts`: TableStyleLight/Medium/Dark, PivotStyleLight/Medium/Dark) as `&'static` data, sorted
// by name (binary search). The strings keep the TS compact format; the code decodes them against the workbook's theme.
//
//   node core/crates/uo-xlsx/js/gen-paint-data.mjs [--ts-root <dir>] [--check]
//
// `--check` fails when the committed file differs from what the frozen TS gives.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { args, crateDir, tsRoot } from './lib/common.mjs';

const a = args();
const sp = join(tsRoot(a), 'sheet', 'packages');
const src = readFileSync(join(sp, 'sheet/src/table-styles-data.ts'), 'utf8').replace(/export const (\w+): [^=]+=/g, 'export const $1 =');
const mod = await import(`data:text/javascript;base64,${Buffer.from(src).toString('base64')}`);
const rec = mod.BUILTIN_TABLE_STYLES;
const rs = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
for (const [k, v] of Object.entries(rec)) if (!/^[\x20-\x7e]+$/.test(k + v)) throw new Error(`non-ASCII in ${k}`);
let out = '// GENERATED by core/crates/uo-xlsx/js/gen-paint-data.mjs from the frozen TS `table-styles-data.ts` — do not edit by hand.\n';
out += '// Built-in table / pivot styles measured in Excel (Workbook.TableStyles(n).TableStyleElements(e)); the compact format is\n';
out += '// `element=prop,prop;…` (f:<colour> fill, c:<colour> font colour, B bold, I italic, l|r|t|b|v|h:<style>:<colour> borders,\n';
out += '// s:<n> stripe size); a colour is a theme index with an optional `/tint`. Sorted by name.\n\n';
out += 'pub static BUILTIN_TABLE_STYLES: &[(&str, &str)] = &[\n';
for (const k of Object.keys(rec).sort()) out += `    (${rs(k)}, ${rs(rec[k])}),\n`;
out += '];\n';
const target = join(crateDir, 'src', 'grid', 'table_style', 'data.rs');
if (a.flag('--check')) {
  if (readFileSync(target, 'utf8') !== out) { console.error('src/grid/table_style/data.rs differs from the frozen TS data'); process.exit(1); }
  console.log('paint data: up to date');
} else {
  writeFileSync(target, out);
  console.log(`paint data: ${Object.keys(rec).length} styles, ${out.length} bytes -> ${target}`);
}
