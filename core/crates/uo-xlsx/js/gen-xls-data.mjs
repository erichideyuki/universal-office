// Generates `src/xls/data.rs`: the tables of the frozen TS `.xls` converter as `&'static` data — the BIFF8 function table
// (`FTAB_SRC` of formula.ts: index → name and fixed argument count) and the measured Excel row-height / digit-width tables
// (`excel-metrics-data.ts`, which drawing.ts uses through grid-metrics.ts to turn the cell anchors of shapes into EMU).
// Numbers and function names only. (The grid port, frontier C3a, holds its own copy of the metrics: unify when it lands.)
//
//   node core/crates/uo-xlsx/js/gen-xls-data.mjs [--ts-root <dir>] [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { args, crateDir, tsRoot } from './lib/common.mjs';

const a = args();
const root = tsRoot(a);
const sp = join(root, 'sheet', 'packages', 'sheet-core', 'src');

async function load(rel) {
  const src = readFileSync(join(sp, rel), 'utf8').replace(/export const (\w+): [^=]+=/g, 'export const $1 =');
  return import(`data:text/javascript;base64,${Buffer.from(src).toString('base64')}`);
}
const rs = (s) => `"${s.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;

const m = await load('excel-metrics-data.ts');
const fsrc = readFileSync(join(sp, 'xls/formula.ts'), 'utf8');
const mm = /const FTAB_SRC = ((?:\s*\+?\s*'[^']*')+);/.exec(fsrc);
if (!mm) throw new Error('FTAB_SRC not found');
const ftab = [...mm[1].matchAll(/'([^']*)'/g)].map((x) => x[1]).join('').split(',').map((e) => {
  const [i, rest] = e.split(':');
  const [name, n] = rest.split('/');
  return [Number(i), name, Number(n)];
});

let out = '//! Tables of the `.xls` converter: the BIFF8 function table and the measured Excel grid metrics.\n';
out += '//! GENERATED by core/crates/uo-xlsx/js/gen-xls-data.mjs from the frozen TS (sheet-core): do not edit by hand.\n\n';
out += '/// `FTAB_SRC` (formula.ts): function index, name, fixed argument count (-1 = variable).\n';
out += `pub static FTAB: [(u16, &str, i8); ${ftab.length}] = [\n`;
for (const [i, n, c] of ftab) out += `    (${i}, ${rs(n)}, ${c}),\n`;
out += '];\n\n';
const table = (name, doc, o) => {
  const keys = Object.keys(o);
  let s = `/// ${doc}\npub static ${name}: [(&str, &str); ${keys.length}] = [\n`;
  for (const k of keys) s += `    (${rs(k)}, ${rs(o[k])}),\n`;
  return `${s}];\n\n`;
};
out += `pub const ROW_PPEM_MIN: i32 = ${m.ROW_PPEM_MIN};\npub const ROW_PPEM_MAX: i32 = ${m.ROW_PPEM_MAX};\npub const MDW_PPEM_MIN: i32 = ${m.MDW_PPEM_MIN};\npub const MDW_PPEM_MAX: i32 = ${m.MDW_PPEM_MAX};\n\n`;
out += table('ROW_PX', 'Row heights (px) by family, ppem 4..96: base62, first value then deltas + 16.', m.ROW_PX);
out += table('ROW_PX_BOLD', 'The same in bold, ppem 4..40 (only the families that differ).', m.ROW_PX_BOLD);
out += table('MDW', 'Maximum digit width (px) by family, ppem 8..32, base62.', m.MDW);
out = out.replace(/\n\n$/, '\n');
const file = join(crateDir, 'src', 'xls', 'data.rs');
if (a.flag('--check')) {
  const cur = readFileSync(file, 'utf8');
  if (cur !== out) { console.error('src/xls/data.rs differs from the frozen TS tables'); process.exit(1); }
  console.log('src/xls/data.rs is current');
} else {
  writeFileSync(file, out);
  console.log(`${file}: ${ftab.length} functions, ${Object.keys(m.ROW_PX).length}+${Object.keys(m.ROW_PX_BOLD).length}+${Object.keys(m.MDW).length} metric families`);
}
