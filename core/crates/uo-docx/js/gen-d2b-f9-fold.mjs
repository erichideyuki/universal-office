// Generates src/session/ops/find/fold.rs: the case-insensitive equivalence classes of a `RegExp` with
// the `i` and `u` flags (ES2025 22.2.2.7.3 Canonicalize with simple case folding), measured on V8 itself
// (Node 24.15, V8 13.6, ICU 77, Unicode 17.0). Two code points match under `/iu` exactly when they are in
// the same class; a class is listed when it has more than one member. Candidates come from the single-code-
// point results of toUpperCase/toLowerCase (both ways); every candidate pair is then confirmed (or
// dropped) by `new RegExp('^' + a + '$', 'iu').test(b)`, so the classes are what V8 matches, not what the
// case mappings suggest (ı and I are linked by toUpperCase but do not match).
//
//   node core/crates/uo-docx/js/gen-d2b-f9-fold.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'session', 'ops', 'find', 'fold.rs');

const parent = new Map();
const find = (x) => { let r = x; while (parent.get(r) !== r) r = parent.get(r); let y = x; while (parent.get(y) !== r) { const n = parent.get(y); parent.set(y, r); y = n; } return r; };
const add = (x) => { if (!parent.has(x)) parent.set(x, x); };
const union = (a, b) => { add(a); add(b); const ra = find(a), rb = find(b); if (ra !== rb) parent.set(Math.max(ra, rb), Math.min(ra, rb)); };
const single = (s) => { const cps = [...s]; return cps.length === 1 ? cps[0].codePointAt(0) : undefined; };

for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  for (const t of [s.toUpperCase(), s.toLowerCase(), s.toUpperCase().toLowerCase(), s.toLowerCase().toUpperCase()]) {
    const o = single(t);
    if (o !== undefined && o !== cp) union(cp, o);
  }
}
const groups = new Map();
for (const x of parent.keys()) { const r = find(x); if (!groups.has(r)) groups.set(r, []); groups.get(r).push(x); }
const esc = (cp) => `\\u{${cp.toString(16)}}`;
const classes = [];
for (const members of groups.values()) {
  members.sort((a, b) => a - b);
  const left = new Set(members);
  for (const a of members) {
    if (!left.has(a)) continue;
    const re = new RegExp(`^${esc(a)}$`, 'iu');
    const cls = members.filter((b) => left.has(b) && re.test(String.fromCodePoint(b)));
    for (const b of cls) left.delete(b);
    // symmetric check
    for (const b of cls) for (const c of cls) if (!new RegExp(`^${esc(b)}$`, 'iu').test(String.fromCodePoint(c))) throw new Error(`not symmetric ${b} ${c}`);
    if (cls.length > 1) classes.push(cls);
  }
}
classes.sort((a, b) => a[0] - b[0]);
const index = [];
const pool = [];
for (const cls of classes) {
  const start = pool.length;
  pool.push(...cls);
  for (const cp of cls) index.push([cp, start, cls.length]);
}
index.sort((a, b) => a[0] - b[0]);
const lines = [];
lines.push('//! GENERATED by `js/gen-d2b-f9-fold.mjs` from V8 itself (Node 24.15, V8 13.6, ICU 77, Unicode 17.0): the');
lines.push('//! equivalence classes of a `RegExp` with the `i` and `u` flags (simple case folding), only the classes with');
lines.push('//! more than one member. Do not edit.');
lines.push('');
lines.push(`/// Members of every class, class after class (${pool.length} code points).`);
lines.push(`pub(super) static POOL: [u32; ${pool.length}] = [`);
for (let i = 0; i < pool.length; i += 12) lines.push(`    ${pool.slice(i, i + 12).map((x) => `0x${x.toString(16).toUpperCase()}`).join(', ')},`);
lines.push('];');
lines.push('');
lines.push('/// `(code point, start in POOL, members)`, sorted by code point.');
lines.push(`pub(super) static INDEX: [(u32, u16, u8); ${index.length}] = [`);
for (let i = 0; i < index.length; i += 6) lines.push(`    ${index.slice(i, i + 6).map(([c, s, n]) => `(0x${c.toString(16).toUpperCase()}, ${s}, ${n})`).join(', ')},`);
lines.push('];');
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`fold.rs: ${classes.length} classes, ${pool.length} code points`);
