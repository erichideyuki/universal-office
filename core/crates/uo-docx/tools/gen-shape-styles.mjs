// Generates the Shape Styles gallery of uo-docx (src/data/shape_styles.rs) from the frozen TS of
// main: `SHAPE_STYLE_PRESETS` of shared/drawingml/src/shape-styles.ts (uo-drawingml gate decision
// G3: the Word-only gallery moved from the shared DrawingML package to uo-docx), evaluated by
// Node (type stripping, the module has no imports) and written as Rust constants. The TS file is
// itself generated from Word measurements (write/tools/textbox-lab/gen-shape-styles.mjs).
//
//   UO_TS_ROOT=<checkout of main> node core/crates/uo-docx/tools/gen-shape-styles.mjs [--check]
//
// Same conventions as gen-data.mjs: deterministic, the file carries the SHA-256 of its source
// (the Rust test `shape_styles_source_unchanged` compares it with the worktree's copy), `--check`
// writes nothing and exits 1 when the file would change (the opt-in regeneration test).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'data', 'shape_styles.rs');
const root = process.env.UO_TS_ROOT ?? (process.argv.includes('--ts-root') ? process.argv[process.argv.indexOf('--ts-root') + 1] : undefined);
if (!root) { console.error('set UO_TS_ROOT to a checkout of main'); process.exit(2); }
const check = process.argv.includes('--check');
const rel = 'shared/drawingml/src/shape-styles.ts';
const file = join(root, rel);

/** A Rust string literal: UTF-8 as is, escapes for `"`, `\` and control characters. */
function lit(s) {
  let o = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"') o += '\\"';
    else if (ch === '\\') o += '\\\\';
    else if (ch === '\n') o += '\\n';
    else if (ch === '\r') o += '\\r';
    else if (ch === '\t') o += '\\t';
    else if (c < 0x20 || c === 0x7f) o += `\\u{${c.toString(16)}}`;
    else if (c >= 0xd800 && c <= 0xdfff) throw new Error('lone surrogate in a data string');
    else o += ch;
  }
  return o + '"';
}

const m = await import(pathToFileURL(file).href);
const table = m.SHAPE_STYLE_PRESETS;
if (!Array.isArray(table) || table.length !== 77) throw new Error(`SHAPE_STYLE_PRESETS: expected 77 entries, got ${table?.length}`);
for (const e of table) if (!Array.isArray(e) || e.length !== 2 || typeof e[0] !== 'string' || typeof e[1] !== 'string') throw new Error('SHAPE_STYLE_PRESETS entry is not [string, string]');

const lines = [
  '// @generated by core/crates/uo-docx/tools/gen-shape-styles.mjs from the frozen TS of main — do not edit.',
  `// source: ${rel} sha256 ${createHash('sha256').update(readFileSync(file)).digest('hex')}`,
  '',
  '//! `shape-styles.ts`: the Shape Styles gallery (Formato da Forma), measured in Word. For style N (1..77, index N-1):',
  '//! the children of `wps:spPr` after the geometry (fill and line; the empty `<a:ln/>` of the theme styles drops the',
  '//! own line and the `lnRef` rules) and the `wps:style` (theme references). 1–42: theme styles; 43–77: presets.',
  '',
  '/// One gallery entry (`[spPr, style]` in the TS).',
  '#[derive(Debug, Clone, Copy, PartialEq, Eq)]',
  'pub struct ShapeStylePreset {',
  '    /// the `wps:spPr` children after the geometry',
  '    pub sp_pr: &\'static str,',
  '    /// the `wps:style` element',
  '    pub style: &\'static str,',
  '}',
  '',
  '/// `SHAPE_STYLE_PRESETS`, in gallery order.',
  'pub const SHAPE_STYLE_PRESETS: &[ShapeStylePreset] = &[',
  ...table.map(([sp, st]) => `    ShapeStylePreset { sp_pr: ${lit(sp)}, style: ${lit(st)} },`),
  '];',
  '',
];
const text = lines.join('\n');
if (check) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('src/data/shape_styles.rs is stale'); process.exit(1); }
  console.log('src/data/shape_styles.rs is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${table.length} styles)`);
}
