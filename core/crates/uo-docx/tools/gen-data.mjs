// Generates the data tables of uo-docx (src/data/*.rs) from the frozen TS of main
// (architecture A2 "Generated data"): the values of the data modules of docx-core, evaluated by
// Node (type stripping, the modules have no imports) and written as Rust constants.
//
//   UO_TS_ROOT=<checkout of main> node core/crates/uo-docx/tools/gen-data.mjs [--check]
//
// Deterministic: the same sources give the same bytes (the files carry the SHA-256 of each
// source, which the Rust test `data_sources_unchanged` compares with the worktree's copy of the
// sources). `--check` writes nothing and exits 1 when a file would change (the regeneration
// diff test, opt-in from `cargo test` with UO_TS_PARITY=1).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'data');
const root = process.env.UO_TS_ROOT ?? (process.argv.includes('--ts-root') ? process.argv[process.argv.indexOf('--ts-root') + 1] : undefined);
if (!root) { console.error('set UO_TS_ROOT to a checkout of main'); process.exit(2); }
const check = process.argv.includes('--check');
const src = (f) => join(root, 'write', 'packages', 'docx-core', 'src', f);
const sha = (f) => createHash('sha256').update(readFileSync(src(f))).digest('hex');

/** A Rust string literal: UTF-8 as is, escapes for `"`, `\` and control characters. */
function lit(s) {
  let o = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"') o += '\\"';
    else if (ch === '\\') o += '\\\\';
    else if (ch === '\n') o += '\\n';
    else if (ch === '\r') o += '\\r';
    else if (ch === '\t') o += '\\t';
    else if (c < 0x20 || c === 0x7f) o += `\\u{${c.toString(16)}}`;
    else if (c >= 0xd800 && c <= 0xdfff) throw new Error('lone surrogate in a data string');
    else o += ch;
  }
  return o + '"';
}

const header = (files) => [
  '// @generated by core/crates/uo-docx/tools/gen-data.mjs from the frozen TS of main — do not edit.',
  ...files.map((f) => `// source: write/packages/docx-core/src/${f} sha256 ${sha(f)}`),
  '',
].join('\n');

const files = new Map();

{
  const m = await import(pathToFileURL(src('word-styles.ts')).href);
  const lines = [header(['word-styles.ts']), '//! `word-styles.ts`: the parts of the blank document and the built-in styles as Word writes them.', ''];
  for (const k of ['WORD_BLANK_STYLES', 'WORD_BLANK_THEME', 'WORD_BLANK_SETTINGS', 'WORD_BLANK_FONT_TABLE', 'WORD_BLANK_SECTPR']) {
    lines.push(`/// \`${k}\``, `pub const ${k}: &str = ${lit(m[k])};`, '');
  }
  lines.push('/// `WORD_BUILTIN_STYLES`: (canonical `w:name`, pt-BR name, `w:style`, the linked `…Char` `w:style`).');
  lines.push('pub const WORD_BUILTIN_STYLES: &[(&str, &str, &str, Option<&str>)] = &[');
  for (const [a, b, c, d] of m.WORD_BUILTIN_STYLES) lines.push(`    (${lit(a)}, ${lit(b)}, ${lit(c)}, ${d === undefined ? 'None' : `Some(${lit(d)})`}),`);
  lines.push('];', '');
  files.set('word_styles.rs', lines.join('\n'));
}

{
  const m = await import(pathToFileURL(src('style-names-es.ts')).href);
  const lines = [header(['style-names-es.ts']), '//! `style-names-es.ts`: the Spanish display names of the built-in styles (`BUILTIN_STYLE_NAMES_ES`, evaluated, JS object order).', '//! `TABLE_FIXED`/`TABLE_FAMILY` (regex rules) are code, ported by frontier R2.', ''];
  lines.push('pub const BUILTIN_STYLE_NAMES_ES: &[(&str, &str)] = &[');
  for (const [k, v] of Object.entries(m.BUILTIN_STYLE_NAMES_ES)) lines.push(`    (${lit(k)}, ${lit(v)}),`);
  lines.push('];', '');
  files.set('style_names_es.rs', lines.join('\n'));
}

{
  const m = await import(pathToFileURL(src('table-styles-builtin.ts')).href);
  const lines = [header(['table-styles-builtin.ts']), '//! `table-styles-builtin.ts`: the built-in table styles of Word 365 pt-BR (`BUILTIN_TABLE_STYLES`).', ''];
  lines.push('/// One built-in table style source (`BuiltinTableStyleSrc`).', '#[derive(Debug, Clone, Copy, PartialEq, Eq)]', 'pub struct BuiltinTableStyleSrc {',
    '    pub name: &\'static str,', '    pub local: &\'static str,', '    pub xml: &\'static str,', '    /// `accents` (`None` when the TS object has no such key)', '    pub accents: Option<&\'static [u8]>,', '    /// `modern: 1`', '    pub modern: bool,', '}', '');
  lines.push('pub const BUILTIN_TABLE_STYLES: &[BuiltinTableStyleSrc] = &[');
  for (const s of m.BUILTIN_TABLE_STYLES) {
    const extra = Object.keys(s).filter((k) => !['name', 'local', 'xml', 'accents', 'modern'].includes(k));
    if (extra.length) throw new Error(`unknown key ${extra}`);
    lines.push(`    BuiltinTableStyleSrc { name: ${lit(s.name)}, local: ${lit(s.local)}, xml: ${lit(s.xml)}, accents: ${s.accents ? `Some(&[${s.accents.join(', ')}])` : 'None'}, modern: ${s.modern === 1} },`);
  }
  lines.push('];', '');
  files.set('table_styles_builtin.rs', lines.join('\n'));
}

let changed = 0;
for (const [name, text] of files) {
  const p = join(out, name);
  let old = '';
  try { old = readFileSync(p, 'utf8'); } catch { /* new */ }
  if (old !== text) {
    changed++;
    if (check) console.error(`stale: src/data/${name}`);
    else writeFileSync(p, text);
  }
}
if (check && changed) process.exit(1);
console.log(`${check ? 'checked' : 'wrote'} ${files.size} files, ${changed} ${check ? 'stale' : 'changed'}`);
