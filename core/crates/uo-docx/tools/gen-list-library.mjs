// Node 24 strips the types of the .ts file on import.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = process.env.UO_TS_ROOT ?? 'D:/Projects/OfficeNext/.claude/worktrees/clickcompliance-docx';
const file = join(root, 'write/packages/editor/src/list-library.ts');
const m = await import(pathToFileURL(file).href);
const sha = createHash('sha256').update(readFileSync(file)).digest('hex');
const lit = (s) => `"${[...s].map((c) => {
  const cp = c.codePointAt(0);
  if (c === '"') return '\\"';
  if (c === '\\') return '\\\\';
  if (cp < 0x20 || cp > 0x7e) return `\\u{${cp.toString(16)}}`;
  return c;
}).join('')}"`;
const table = (name, rows) => `pub const ${name}: &[LibraryList] = &[\n${rows.map((r) => `    LibraryList {\n        multi_level_type: ${lit(r.multiLevelType)},\n        tmpl: ${r.tmpl === undefined ? 'None' : `Some(${lit(r.tmpl)})`},\n        linked: ${r.linked},\n        levels: &[\n${r.levels.map((l) => `            ${lit(l)},\n`).join('')}        ],\n    },\n`).join('')}];\n`;
const out = `// GENERATED by tools/gen-list-library.mjs from write/packages/editor/src/list-library.ts (sha256 ${sha}); do not edit.\n`
  + `//! The Bullet, Number and Multilevel libraries as Word writes them (\`list-library.ts\`): the \`w:lvl\` of each level.\n\n`
