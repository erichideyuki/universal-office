  + `${table('BULLET_LIBRARY', m.BULLET_LIBRARY)}\n${table('NUMBER_LIBRARY', m.NUMBER_LIBRARY)}\n${table('MULTILEVEL_LIBRARY', m.MULTILEVEL_LIBRARY)}`;
const target = join(here, '..', 'src/session/ops/lists/library.rs');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) { console.error('library.rs is out of date'); process.exit(1); }
} else writeFileSync(target, out, { encoding: 'utf8' });
console.log(`library.rs: ${m.BULLET_LIBRARY.length} bullets, ${m.NUMBER_LIBRARY.length} numbers, ${m.MULTILEVEL_LIBRARY.length} multilevel`);
