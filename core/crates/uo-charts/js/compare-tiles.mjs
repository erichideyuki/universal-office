// C-6: the chart op streams that `RecCanvas` (the native recorder of the C-3..C-5 replay) cannot print — the charts that paint a
// picture TILE — compared through the PRODUCT path: the Rust engine emitted each into a Slides display list
// (`tests/c6_tiles.rs`, `UO_C6_TILES_OUT`), this script paints the list with the TS interpreter (`paint-slides.ts`, `tilePattern` and
// `flippedTile` run there) over the recording context and checks the draw-form digest against the facet `ops.<view>.<sel>` of
// `charts-c1a.capture`.
//
//   UO_C6_TILES_OUT=D:/tmp/c6tiles cargo test -p uo-charts --test c6_tiles -- --nocapture
//   node core/crates/uo-charts/js/compare-tiles.mjs --frames D:/tmp/c6tiles [--show 5]
//
// The pictures of a chart are regenerated by the generator (`buildChart`: same seed, same bytes); media row i of a frame is the chart's
// picture i (the order of the capture's `images`). A facet whose expected value is an error (`err:`) is counted, not compared: the
// engine threw on both sides and the list holds what was drawn before.
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCapture } from '../../uo-testkit/js/testkit.mjs';
import { args } from '../../uo-pptx/js/lib/common.mjs';
import { digest, form } from '../../uo-pptx/js/lib/opstream.mjs';
import { recordList } from '../../uo-pptx/js/lib/rust-paint.mjs';
import { decodeSlidesList, newTables } from '../../uo-wasm/js/gen/slides.ts';
import { SEED_BASE, buildChart } from './gen/charts.mjs';

const draw = (text) => form(text.split('\n').filter(Boolean), 'draw');

const here = dirname(fileURLToPath(import.meta.url));
const a = args();
const dir = a.opt('--frames');
if (!dir || !existsSync(dir)) {
  console.error('usage: compare-tiles.mjs --frames <dir written by tests/c6_tiles.rs> [--show n]');
  process.exit(2);
}
const show = Number(a.opt('--show', '5'));
const only = a.opt('--only');
const dump = a.opt('--dump');
const cap = readCapture(join(here, '..', 'tests', 'captures', 'charts-c1a.capture'));
const index = new Map(readFileSync(join(dir, 'index.tsv'), 'utf8').split('\n').filter(Boolean).map((l) => {
  const [key, view, sel, result] = l.split('\t');
  return [`${key}|${view}|${sel}`, result];
}));

/** the draw-form line count of the list equals the facet's (the accepted difference changes numbers, never the lines) */
function sameShape(text, facet) {
  return String(draw(text).length) === facet.split(':')[0];
}

const built = new Map();
function chartOf(key) {
  if (!built.has(key)) built.set(key, buildChart(SEED_BASE + Number(key.slice(key.lastIndexOf('/') + 1))));
  return built.get(key);
}

// charts whose poly/power trendline is the `Math.pow` platform difference (record G1 of uo-jsnum.md, `tests/support/facets.rs` POW_FACETS):
// the stream has the same lines and differs by 1e-12 in the sampled curve; accepted BY NAME, never by tolerance
const POW_CHARTS = new Set(['gen/c1a/0007', 'gen/c1a/0010', 'gen/c1a/0336', 'gen/c1a/0409', 'gen/c1a/0459', 'gen/c1a/0471', 'gen/c1a/0503']);
const stats = { frames: 0, equal: 0, accepted: 0, different: 0, errFacets: 0, paintErrors: 0, noFacet: 0, decodeErrors: 0 };
let shown = 0;
for (const name of readdirSync(dir).filter((n) => n.endsWith('.uolc')).sort()) {
  const [stem, view, sel] = name.slice(0, -'.uolc'.length).split('.');
  const key = stem.replace(/__/g, '/');
  if (only && !key.includes(only)) continue;
  const facet = cap.records.get(key)?.get(`ops.${view}.${sel}`);
  if (facet === undefined) { stats.noFacet++; continue; }
  stats.frames++;
  if (facet.startsWith('err:')) { stats.errFacets++; continue; }
  const buf = readFileSync(join(dir, name));
  const cw = buf.readUInt32LE(4), ch = buf.readUInt32LE(8), n = buf.readUInt32LE(12);
  const tables = newTables();
  let list;
  try { list = decodeSlidesList(new Uint8Array(buf.subarray(16, 16 + n)), tables); } catch (e) { stats.decodeErrors++; console.log(`decode-error ${key} ${view}.${sel}: ${e?.message ?? e}`); continue; }
  const images = Object.values(chartOf(key).images);
  const r = recordList({
    list, tables, width: cw, height: ch, caps: { roundRect: true, strictFont: true },
    media: (idx) => images[idx]?.bytes ?? null,
  });
  if (r.error) { stats.paintErrors++; console.log(`paint-error ${key} ${view}.${sel}: ${r.error}`); }
  if (dump) (await import('node:fs')).writeFileSync(join(dump, `${stem}.${view}.${sel}.txt`), r.text);
  const d = await digest(r.text);
  const got = `${d.lines}:${d.sha}`;
  if (got === facet) stats.equal++;
  else if (POW_CHARTS.has(key) && sameShape(r.text, facet)) stats.accepted++;
  else {
    stats.different++;
    if (shown++ < show) console.log(`DIFFERS ${key} ${view}.${sel}: capture ${facet}, list ${got} (${index.get(`${key}|${view}|${sel}`)})`);
  }
}
console.log(`${stats.frames} tile facets compared through the interpreter: ${stats.equal} equal, ${stats.accepted} accepted by name (Math.pow), ${stats.different} different; ` +
  `${stats.errFacets} error facets (not compared), ${stats.paintErrors} paint errors, ${stats.decodeErrors} decode errors, ${stats.noFacet} without a facet`);
process.exit(stats.different || stats.paintErrors || stats.decodeErrors ? 1 : 0);
